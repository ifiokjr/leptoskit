// Writes a size tier into a copy of the Flutter tier shell
// (`arena/apps/flutter/tier`): one Dart file per screen under `lib/screens/`,
// a shared `lib/screen_scaffold.dart`, and `lib/main.dart`, which holds the
// current screen in state and builds the home menu or that screen. No routing
// package.

import {
	type CounterScreen,
	type DetailScreen,
	type FormScreen,
	type ListScreen,
	quoted,
	type Screen,
	type TierApp,
	type TierEmitter,
} from "../tiers.ts";

const GENERATED = "// Generated by scripts/arena/emit/flutter.ts. Do not edit.";

/** `counter001` → `Counter001Screen`: the widget class name. */
function widgetName(screen: Screen): string {
	return `${screen.id[0].toUpperCase()}${screen.id.slice(1)}Screen`;
}

function lines(...parts: (string | string[])[]): string {
	return `${parts.flat().join("\n")}\n`;
}

/** The constructor and `onBack` field every screen widget has. */
function screenFields(screen: Screen): string[] {
	const name = widgetName(screen);
	return [
		`  const ${name}({super.key, this.onBack});`,
		"",
		"  /// Returns to the home menu; null when this is the app's only screen.",
		"  final VoidCallback? onBack;",
	];
}

function counter(screen: CounterScreen): string {
	const name = widgetName(screen);
	return lines(
		GENERATED,
		"import 'package:flutter/material.dart';",
		"",
		"import '../screen_scaffold.dart';",
		"",
		`class ${name} extends StatefulWidget {`,
		screenFields(screen),
		"",
		"  @override",
		`  State<${name}> createState() => _${name}State();`,
		"}",
		"",
		`class _${name}State extends State<${name}> {`,
		"  int _count = 0;",
		"",
		"  @override",
		"  Widget build(BuildContext context) {",
		"    return ScreenScaffold(",
		`      title: ${quoted(screen.title)},`,
		"      onBack: widget.onBack,",
		"      children: [",
		"        Text('Count: $_count', style: const TextStyle(fontSize: 18)),",
		"        const SizedBox(height: 12),",
		"        FilledButton(",
		`          onPressed: () => setState(() => _count += ${screen.step}),`,
		`          child: const Text(${quoted(`Add ${screen.step}`)}),`,
		"        ),",
		"      ],",
		"    );",
		"  }",
		"}",
	);
}

function list(screen: ListScreen): string {
	const name = widgetName(screen);
	return lines(
		GENERATED,
		"import 'package:flutter/material.dart';",
		"",
		"import '../screen_scaffold.dart';",
		"",
		"const List<({String title, String subtitle})> _rows = [",
		screen.rows.map((row) =>
			`  (title: ${quoted(row.title)}, subtitle: ${quoted(row.subtitle)}),`
		),
		"];",
		"",
		`class ${name} extends StatelessWidget {`,
		screenFields(screen),
		"",
		"  @override",
		"  Widget build(BuildContext context) {",
		"    return ScreenScaffold(",
		`      title: ${quoted(screen.title)},`,
		"      onBack: onBack,",
		"      children: [",
		"        for (final row in _rows)",
		"          ListTile(",
		"            contentPadding: EdgeInsets.zero,",
		"            title: Text(row.title),",
		"            subtitle: Text(row.subtitle),",
		"          ),",
		"      ],",
		"    );",
		"  }",
		"}",
	);
}

function form(screen: FormScreen): string {
	const name = widgetName(screen);
	return lines(
		GENERATED,
		"import 'package:flutter/material.dart';",
		"",
		"import '../screen_scaffold.dart';",
		"",
		"/// Each field's label, minimum length, and the message shown when it is too short.",
		"const List<({String label, int minLength, String tooShort})> _fields = [",
		screen.fields.map((field) => [
			"  (",
			`    label: ${quoted(field.label)},`,
			`    minLength: ${field.minLength},`,
			`    tooShort: ${
				quoted(`${field.label} needs at least ${field.minLength} characters`)
			},`,
			"  ),",
		]).flat(),
		"];",
		"",
		`class ${name} extends StatefulWidget {`,
		screenFields(screen),
		"",
		"  @override",
		`  State<${name}> createState() => _${name}State();`,
		"}",
		"",
		`class _${name}State extends State<${name}> {`,
		"  final List<TextEditingController> _controllers = [",
		"    for (final _ in _fields) TextEditingController(),",
		"  ];",
		"  List<String> _messages = const [];",
		"",
		"  void _submit() {",
		"    final errors = [",
		"      for (final (index, field) in _fields.indexed)",
		"        if (_controllers[index].text.length < field.minLength) field.tooShort,",
		"    ];",
		"    final values = _controllers.map((controller) => controller.text);",
		"    setState(() {",
		"      _messages = errors.isEmpty ? ['Saved: ${values.join(', ')}'] : errors;",
		"    });",
		"  }",
		"",
		"  @override",
		"  void dispose() {",
		"    for (final controller in _controllers) {",
		"      controller.dispose();",
		"    }",
		"    super.dispose();",
		"  }",
		"",
		"  @override",
		"  Widget build(BuildContext context) {",
		"    return ScreenScaffold(",
		`      title: ${quoted(screen.title)},`,
		"      onBack: widget.onBack,",
		"      children: [",
		"        for (final (index, field) in _fields.indexed)",
		"          Padding(",
		"            padding: const EdgeInsets.only(bottom: 12),",
		"            child: TextField(",
		"              controller: _controllers[index],",
		"              decoration: InputDecoration(labelText: field.label),",
		"            ),",
		"          ),",
		"        FilledButton(",
		"          onPressed: _submit,",
		`          child: const Text(${quoted(screen.submitLabel)}),`,
		"        ),",
		"        for (final message in _messages) Text(message),",
		"      ],",
		"    );",
		"  }",
		"}",
	);
}

function detail(screen: DetailScreen): string {
	const name = widgetName(screen);
	return lines(
		GENERATED,
		"import 'package:flutter/material.dart';",
		"",
		"import '../screen_scaffold.dart';",
		"",
		"const List<String> _paragraphs = [",
		screen.paragraphs.map((paragraph) => `  ${quoted(paragraph)},`),
		"];",
		"",
		`class ${name} extends StatelessWidget {`,
		screenFields(screen),
		"",
		"  @override",
		"  Widget build(BuildContext context) {",
		"    return ScreenScaffold(",
		`      title: ${quoted(screen.title)},`,
		"      onBack: onBack,",
		"      children: [",
		"        for (final paragraph in _paragraphs)",
		"          Padding(",
		"            padding: const EdgeInsets.only(bottom: 12),",
		"            child: Text(paragraph),",
		"          ),",
		"      ],",
		"    );",
		"  }",
		"}",
	);
}

function screenSource(screen: Screen): string {
	switch (screen.kind) {
		case "counter":
			return counter(screen);
		case "list":
			return list(screen);
		case "form":
			return form(screen);
		case "detail":
			return detail(screen);
	}
}

/** The layout every screen shares: a scroll view with an optional Back button and the title. */
const SCREEN_SCAFFOLD = lines(
	GENERATED,
	"import 'package:flutter/material.dart';",
	"",
	"/// A screen of the tier app: a scroll view holding the Back button (when",
	"/// the app has a home menu to return to), the title, and the screen's content.",
	"class ScreenScaffold extends StatelessWidget {",
	"  const ScreenScaffold({",
	"    super.key,",
	"    required this.title,",
	"    required this.onBack,",
	"    required this.children,",
	"  });",
	"",
	"  final String title;",
	"  final VoidCallback? onBack;",
	"  final List<Widget> children;",
	"",
	"  @override",
	"  Widget build(BuildContext context) {",
	"    return Scaffold(",
	"      body: SafeArea(",
	"        child: ListView(",
	"          padding: const EdgeInsets.all(16),",
	"          children: [",
	"            if (onBack case final onBack?)",
	"              Align(",
	"                alignment: Alignment.centerLeft,",
	"                child: TextButton(onPressed: onBack, child: const Text('Back')),",
	"              ),",
	"            Padding(",
	"              padding: const EdgeInsets.only(bottom: 12),",
	"              child: Text(",
	"                title,",
	"                style: const TextStyle(",
	"                  fontSize: 22,",
	"                  fontWeight: FontWeight.w600,",
	"                ),",
	"              ),",
	"            ),",
	"            ...children,",
	"          ],",
	"        ),",
	"      ),",
	"    );",
	"  }",
	"}",
);

function main(app: TierApp): string {
	const imports = app.screens.map((screen) =>
		`import 'screens/${screen.id}.dart';`
	);
	const head = [
		GENERATED,
		"import 'package:flutter/material.dart';",
		"",
		...imports,
		"",
		"void main() => runApp(const TierApp());",
		"",
		"class TierApp extends StatelessWidget {",
		"  const TierApp({super.key});",
		"",
		"  @override",
		"  Widget build(BuildContext context) {",
		"    return MaterialApp(",
		`      title: ${quoted(app.title)},`,
		"      debugShowCheckedModeBanner: false,",
		"      theme: ThemeData(colorSchemeSeed: const Color(0xFF3D5A80)),",
		app.screens.length === 1
			? `      home: const ${widgetName(app.screens[0])}(),`
			: "      home: const _Navigator(),",
		"    );",
		"  }",
		"}",
	];
	if (app.screens.length === 1) return lines(head);

	return lines(
		head,
		"",
		"/// Every screen of the app, in home menu order.",
		"enum _Screen {",
		app.screens.map((screen, index) =>
			`  ${screen.id}(${quoted(screen.title)})${
				index === app.screens.length - 1 ? ";" : ","
			}`
		),
		"",
		"  const _Screen(this.title);",
		"",
		"  final String title;",
		"}",
		"",
		"/// Navigation is a piece of state: the open screen, or null for the home menu.",
		"class _Navigator extends StatefulWidget {",
		"  const _Navigator();",
		"",
		"  @override",
		"  State<_Navigator> createState() => _NavigatorState();",
		"}",
		"",
		"class _NavigatorState extends State<_Navigator> {",
		"  _Screen? _current;",
		"",
		"  void _open(_Screen? screen) => setState(() => _current = screen);",
		"",
		"  @override",
		"  Widget build(BuildContext context) {",
		"    void back() => _open(null);",
		"    return switch (_current) {",
		"      null => Scaffold(",
		"        body: SafeArea(",
		"          child: ListView(",
		"            padding: const EdgeInsets.all(16),",
		"            children: [",
		"              Padding(",
		"                padding: const EdgeInsets.only(bottom: 12),",
		"                child: Text(",
		`                  ${quoted(app.title)},`,
		"                  style: const TextStyle(",
		"                    fontSize: 24,",
		"                    fontWeight: FontWeight.w600,",
		"                  ),",
		"                ),",
		"              ),",
		"              for (final screen in _Screen.values)",
		"                TextButton(",
		"                  onPressed: () => _open(screen),",
		"                  child: Text(screen.title),",
		"                ),",
		"            ],",
		"          ),",
		"        ),",
		"      ),",
		app.screens.map((screen) =>
			`      _Screen.${screen.id} => ${widgetName(screen)}(onBack: back),`
		),
		"    };",
		"  }",
		"}",
	);
}

export const emitter: TierEmitter = {
	framework: "flutter",
	async emit(app: TierApp, projectDir: string): Promise<void> {
		const lib = `${projectDir}/lib`;
		// `lib/screens` is wholly generated; clear it so a smaller tier never
		// inherits a larger tier's screens.
		await Deno.remove(`${lib}/screens`, { recursive: true }).catch(
			(error: unknown) => {
				if (!(error instanceof Deno.errors.NotFound)) throw error;
			},
		);
		await Deno.mkdir(`${lib}/screens`, { recursive: true });
		await Promise.all([
			...app.screens.map((screen) =>
				Deno.writeTextFile(
					`${lib}/screens/${screen.id}.dart`,
					screenSource(screen),
				)
			),
			Deno.writeTextFile(`${lib}/screen_scaffold.dart`, SCREEN_SCAFFOLD),
			Deno.writeTextFile(`${lib}/main.dart`, main(app)),
		]);
	},
};
