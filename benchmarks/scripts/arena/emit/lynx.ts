// Writes a size tier into a copy of the Lynx tier shell
// (`arena/apps/lynx/tier`): one ReactLynx component per screen under
// `src/screens/`, and `src/App.tsx`, which holds the current screen in state
// and renders the home menu or that screen. No navigation library. Buttons
// are tappable `<view>`s, the way ReactLynx apps write them; styles live in
// the shell's `src/App.css`.

import {
	type CounterScreen,
	type DetailScreen,
	type FormScreen,
	type ListScreen,
	quoted,
	type Screen,
	type TierApp,
	type TierEmitter,
} from "../tiers.ts";

const GENERATED = "// Generated by scripts/arena/emit/lynx.ts. Do not edit.";

/** `counter001` → `Counter001`: the component and file name. */
function componentName(screen: Screen): string {
	return screen.id[0].toUpperCase() + screen.id.slice(1);
}

function lines(...parts: (string | string[])[]): string {
	return `${parts.flat().join("\n")}\n`;
}

const SCREEN_PROPS = "{ onBack }: { onBack?: () => void }";

/** A tappable view with a label: ReactLynx has no button element. */
function button(label: string, onTap: string, indent: string): string[] {
	return [
		`${indent}<view className="button" bindtap={${onTap}}>`,
		`${indent}\t<text className="button-label">{${quoted(label)}}</text>`,
		`${indent}</view>`,
	];
}

/** The Back button, when the screen can go back, then the screen's heading. */
function screenHeader(screen: Screen, indent: string): string[] {
	return [
		`${indent}{onBack !== undefined && (`,
		...button("Back", "onBack", `${indent}\t`),
		`${indent})}`,
		`${indent}<text className="title">{${quoted(screen.title)}}</text>`,
	];
}

function counter(screen: CounterScreen): string {
	const name = componentName(screen);
	return lines(
		GENERATED,
		'import { useState } from "@lynx-js/react";',
		"",
		`export function ${name}(${SCREEN_PROPS}) {`,
		"\tconst [count, setCount] = useState(0);",
		"\treturn (",
		'\t\t<view className="content">',
		screenHeader(screen, "\t\t\t"),
		'\t\t\t<text className="count">{`Count: ${count}`}</text>',
		button(
			`Add ${screen.step}`,
			`() => setCount(count + ${screen.step})`,
			"\t\t\t",
		),
		"\t\t</view>",
		"\t);",
		"}",
	);
}

function list(screen: ListScreen): string {
	const name = componentName(screen);
	return lines(
		GENERATED,
		"const ROWS = [",
		screen.rows.map((row) =>
			`\t{ title: ${quoted(row.title)}, subtitle: ${quoted(row.subtitle)} },`
		),
		"];",
		"",
		`export function ${name}(${SCREEN_PROPS}) {`,
		"\treturn (",
		'\t\t<scroll-view className="screen" scroll-orientation="vertical">',
		'\t\t\t<view className="content">',
		screenHeader(screen, "\t\t\t\t"),
		"\t\t\t\t{ROWS.map((row) => (",
		'\t\t\t\t\t<view key={row.title} className="row">',
		'\t\t\t\t\t\t<text className="row-title">{row.title}</text>',
		'\t\t\t\t\t\t<text className="row-subtitle">{row.subtitle}</text>',
		"\t\t\t\t\t</view>",
		"\t\t\t\t))}",
		"\t\t\t</view>",
		"\t\t</scroll-view>",
		"\t);",
		"}",
	);
}

function form(screen: FormScreen): string {
	const name = componentName(screen);
	const fields = screen.fields;
	const initial = fields.map((field) => `${field.name}: ""`).join(", ");
	const saved = fields.map((field) => `\${values.${field.name}}`).join(", ");
	return lines(
		GENERATED,
		'import { useState } from "@lynx-js/react";',
		"",
		`export function ${name}(${SCREEN_PROPS}) {`,
		`\tconst [values, setValues] = useState({ ${initial} });`,
		"\tconst [messages, setMessages] = useState<string[]>([]);",
		"",
		"\tconst submit = () => {",
		"\t\tconst errors: string[] = [];",
		fields.map((field) =>
			[
				`\t\tif (values.${field.name}.length < ${field.minLength}) {`,
				`\t\t\terrors.push(${
					quoted(`${field.label} needs at least ${field.minLength} characters`)
				});`,
				"\t\t}",
			].join("\n")
		),
		`\t\tsetMessages(errors.length > 0 ? errors : [\`Saved: ${saved}\`]);`,
		"\t};",
		"",
		"\treturn (",
		'\t\t<scroll-view className="screen" scroll-orientation="vertical">',
		'\t\t\t<view className="content">',
		screenHeader(screen, "\t\t\t\t"),
		fields.map((field) =>
			[
				'\t\t\t\t<view className="field">',
				`\t\t\t\t\t<text className="label">{${quoted(field.label)}}</text>`,
				"\t\t\t\t\t<input",
				'\t\t\t\t\t\tclassName="input"',
				`\t\t\t\t\t\tbindinput={(event) => setValues((current) => ({ ...current, ${field.name}: event.detail.value }))}`,
				"\t\t\t\t\t/>",
				"\t\t\t\t</view>",
			].join("\n")
		),
		button(screen.submitLabel, "submit", "\t\t\t\t"),
		"\t\t\t\t{messages.map((message) => (",
		'\t\t\t\t\t<text key={message} className="message">{message}</text>',
		"\t\t\t\t))}",
		"\t\t\t</view>",
		"\t\t</scroll-view>",
		"\t);",
		"}",
	);
}

function detail(screen: DetailScreen): string {
	const name = componentName(screen);
	return lines(
		GENERATED,
		"const PARAGRAPHS = [",
		screen.paragraphs.map((paragraph) => `\t${quoted(paragraph)},`),
		"];",
		"",
		`export function ${name}(${SCREEN_PROPS}) {`,
		"\treturn (",
		'\t\t<scroll-view className="screen" scroll-orientation="vertical">',
		'\t\t\t<view className="content">',
		screenHeader(screen, "\t\t\t\t"),
		"\t\t\t\t{PARAGRAPHS.map((paragraph) => (",
		'\t\t\t\t\t<text key={paragraph} className="paragraph">{paragraph}</text>',
		"\t\t\t\t))}",
		"\t\t\t</view>",
		"\t\t</scroll-view>",
		"\t);",
		"}",
	);
}

function screenSource(screen: Screen): string {
	switch (screen.kind) {
		case "counter":
			return counter(screen);
		case "list":
			return list(screen);
		case "form":
			return form(screen);
		case "detail":
			return detail(screen);
	}
}

function screenImport(screen: Screen): string {
	const name = componentName(screen);
	return `import { ${name} } from "./screens/${name}.js";`;
}

/** One screen renders directly: no menu and no Back button. */
function singleScreenApp(screen: Screen): string {
	return lines(
		GENERATED,
		'import "./App.css";',
		screenImport(screen),
		"",
		"export function App() {",
		"\treturn (",
		'\t\t<view className="root">',
		`\t\t\t<${componentName(screen)} />`,
		"\t\t</view>",
		"\t);",
		"}",
	);
}

function menuApp(app: TierApp): string {
	return lines(
		GENERATED,
		'import { useState } from "@lynx-js/react";',
		"",
		'import "./App.css";',
		app.screens.map(screenImport),
		"",
		"type ScreenId =",
		app.screens.map((screen, index) =>
			`\t| ${quoted(screen.id)}${index === app.screens.length - 1 ? ";" : ""}`
		),
		"",
		"const MENU: { id: ScreenId; title: string }[] = [",
		app.screens.map((screen) =>
			`\t{ id: ${quoted(screen.id)}, title: ${quoted(screen.title)} },`
		),
		"];",
		"",
		"/** The current screen is state; null is the home menu. */",
		"export function App() {",
		"\tconst [screen, setScreen] = useState<ScreenId | null>(null);",
		"\tconst back = () => setScreen(null);",
		"\treturn (",
		'\t\t<view className="root">',
		"\t\t\t{screen === null",
		"\t\t\t\t? (",
		'\t\t\t\t\t<scroll-view className="screen" scroll-orientation="vertical">',
		'\t\t\t\t\t\t<view className="content">',
		`\t\t\t\t\t\t\t<text className="app-title">{${quoted(app.title)}}</text>`,
		"\t\t\t\t\t\t\t{MENU.map((item) => (",
		'\t\t\t\t\t\t\t\t<view key={item.id} className="button" bindtap={() => setScreen(item.id)}>',
		'\t\t\t\t\t\t\t\t\t<text className="button-label">{item.title}</text>',
		"\t\t\t\t\t\t\t\t</view>",
		"\t\t\t\t\t\t\t))}",
		"\t\t\t\t\t\t</view>",
		"\t\t\t\t\t</scroll-view>",
		"\t\t\t\t)",
		"\t\t\t\t: renderScreen(screen, back)}",
		"\t\t</view>",
		"\t);",
		"}",
		"",
		"function renderScreen(screen: ScreenId, onBack: () => void) {",
		"\tswitch (screen) {",
		app.screens.map((screen) =>
			`\t\tcase ${quoted(screen.id)}:\n\t\t\treturn <${
				componentName(screen)
			} onBack={onBack} />;`
		),
		"\t}",
		"}",
	);
}

export const emitter: TierEmitter = {
	framework: "lynx",
	async emit(app: TierApp, projectDir: string): Promise<void> {
		const screensDir = `${projectDir}/src/screens`;
		await Deno.remove(screensDir, { recursive: true }).catch(
			(error: unknown) => {
				if (!(error instanceof Deno.errors.NotFound)) throw error;
			},
		);
		await Deno.mkdir(screensDir, { recursive: true });
		for (const screen of app.screens) {
			await Deno.writeTextFile(
				`${screensDir}/${componentName(screen)}.tsx`,
				screenSource(screen),
			);
		}
		const source = app.screens.length === 1
			? singleScreenApp(app.screens[0])
			: menuApp(app);
		await Deno.writeTextFile(`${projectDir}/src/App.tsx`, source);
	},
};
