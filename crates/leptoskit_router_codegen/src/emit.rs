//! Writes `routes.rs`: the module tree over the route files, the `Route` enum,
//! and its `Routable` implementation.

use proc_macro2::TokenStream;
use quote::format_ident;
use quote::quote;

use crate::name::Segment;
use crate::table::Call;
use crate::table::Prop;
use crate::table::Route;
use crate::table::Target;
use crate::tree::Directory;

/// The line that marks a file as generated, so leptoskit never overwrites a
/// `routes.rs` someone wrote by hand.
pub(crate) const MARKER: &str = "@generated by `leptoskit routes`";

/// The full source of `routes.rs`.
pub(crate) fn source(root: &Directory, routes_dir: &str, routes: &[Route]) -> String {
	let modules = modules(root, &format!("{routes_dir}/"));
	let code = routes_code(routes);
	let file = syn::parse2::<syn::File>(quote!(#(#modules)* #code))
		.expect("the generated tokens form a Rust file");
	format!(
		"// {MARKER} from the `{routes_dir}/` directory beside this file.\n// Do not edit it: \
		 change the route files, then run `leptoskit routes` again.\n\n{}",
		prettyplease::unparse(&file)
	)
}

/// `#[path]` modules for every file and directory. A path at the top of
/// `routes.rs` is relative to the directory holding `routes.rs`, so the top
/// level names the routes directory; inside an inline module, it is relative
/// to that module's directory.
fn modules(directory: &Directory, prefix: &str) -> Vec<TokenStream> {
	let mut items = Vec::new();
	for file in &directory.files {
		let path = format!("{prefix}{}", file.disk_name);
		let ident = format_ident!("{}", file.module);
		items.push((file.module.clone(), quote!(#[path = #path] pub mod #ident;)));
	}
	for child in &directory.directories {
		let path = format!("{prefix}{}", child.disk_name);
		let ident = format_ident!("{}", child.module);
		let inner = modules(child, "");
		items.push((
			child.module.clone(),
			quote!(#[path = #path] pub mod #ident { #(#inner)* }),
		));
	}
	// rustfmt orders module declarations by name; emitting them in that order
	// keeps a formatted file identical to a fresh one.
	items.sort_by(|left, right| left.0.cmp(&right.0));
	items.into_iter().map(|(_, item)| item).collect()
}

fn routes_code(routes: &[Route]) -> TokenStream {
	let runtime = quote!(::leptoskit_router);
	let count = proc_macro2::Literal::usize_unsuffixed(routes.len());
	let mut variants = Vec::new();
	let mut re_exports = Vec::new();
	let mut froms = Vec::new();
	let mut assertions = Vec::new();
	let mut table = Vec::new();
	let mut hrefs = Vec::new();

	for (position, route) in routes.iter().enumerate() {
		let index = proc_macro2::Literal::usize_unsuffixed(position);
		let variant = format_ident!("{}", route.variant);
		let doc = format!(" `{}`", crate::pattern_display(&route.segments));
		let segments = route.segments.iter().map(|segment| {
			match segment {
				Segment::Static(text) => quote!(#runtime::Segment::Static(#text)),
				Segment::Param(name) => quote!(#runtime::Segment::Param(#name)),
				Segment::OptionalParam(name) => quote!(#runtime::Segment::OptionalParam(#name)),
				Segment::Rest(name) => quote!(#runtime::Segment::Rest(#name)),
				Segment::OptionalRest(name) => quote!(#runtime::Segment::OptionalRest(#name)),
			}
		});
		let pattern = quote!(#runtime::Pattern::new(&[#(#segments),*]));
		// A route without fields is matched by its pattern alone; one with
		// fields reads them from the captures and the query.
		let unit = quote!(|_, _| ::core::option::Option::Some(Route::#variant));
		let decode = quote! {
			|captures, url| #runtime::__private::decode(captures, url).ok().map(Route::#variant)
		};

		let module_path = route
			.page_call
			.modules
			.iter()
			.map(|module| format_ident!("{}", module));
		match &route.target {
			Target::Unit => {
				variants.push(quote!(#[doc = #doc] #variant));
				table.push(quote!((#pattern, #unit)));
				hrefs.push(quote!(Self::#variant => ROUTES[#index].0.static_href()));
			}
			Target::Struct {
				name,
				unit: is_unit,
			} => {
				let name = format_ident!("{}", name);
				// Re-exported at the top of the routes module, so everything
				// below names the struct directly. Struct names are unique:
				// each one is a variant name.
				re_exports.push(quote!(pub use #(#module_path)::*::#name;));
				for param in route.params() {
					let message = format!("`{name}` needs a field named `{param}`");
					assertions.push(quote! {
						const _: () = #runtime::__private::require_field(
							<#name as #runtime::RouteParams>::FIELDS,
							#param,
							#message,
						);
					});
				}
				if *is_unit {
					variants.push(quote!(#[doc = #doc] #variant));
					froms.push(quote! {
						impl ::core::convert::From<#name> for Route {
							fn from(_: #name) -> Self {
								Self::#variant
							}
						}
					});
					table.push(quote!((#pattern, #unit)));
					hrefs.push(quote!(Self::#variant => ROUTES[#index].0.static_href()));
				} else {
					variants.push(quote!(#[doc = #doc] #variant(#name)));
					froms.push(quote! {
						impl ::core::convert::From<#name> for Route {
							fn from(route: #name) -> Self {
								Self::#variant(route)
							}
						}
					});
					table.push(quote!((#pattern, #decode)));
					hrefs.push(quote!(Self::#variant(route) => ROUTES[#index].0.href(route)));
				}
			}
			Target::NotFound => {
				variants.push(quote!(#[doc = #doc] #variant(#runtime::NotFound)));
				table.push(quote!((#pattern, #decode)));
				hrefs.push(quote!(Self::#variant(route) => ROUTES[#index].0.href(route)));
			}
		}
	}

	let render = render_code(routes);

	quote! {
		#(#re_exports)*

		/// Every route in the app, one variant per route file. Parse a URL with
		/// `Route::parse`, and write one with `href`, through
		/// `leptoskit_router::Routable`.
		#[derive(Clone, Debug, PartialEq)]
		pub enum Route {
			#(#variants,)*
		}

		#(#froms)*

		#(#assertions)*

		/// Each route's pattern and how to read the route from a match, most
		/// specific first.
		const ROUTES: [(#runtime::Pattern, #runtime::__private::ReadRoute<Route>); #count] = [
			#(#table),*
		];

		impl #runtime::Routable for Route {
			fn from_url(
				url: &#runtime::RouteUrl,
			) -> ::core::result::Result<Self, #runtime::NoMatch> {
				ROUTES
					.iter()
					.find_map(|(pattern, read)| read(&pattern.capture(url.segments())?, url))
					.ok_or(#runtime::NoMatch)
			}

			fn href(&self) -> #runtime::Href {
				match self {
					#(#hrefs,)*
				}
			}
		}

		/// The app's router: pages and layouts that take a `navigation` prop
		/// receive it, to navigate with and to build links.
		pub type Navigation = #runtime::Router<Route>;

		#render
	}
}

/// `Render for Route`: each route calls its page, then each layout above it
/// from the innermost out, passing the props each one declares.
fn render_code(routes: &[Route]) -> TokenStream {
	let private = quote!(::leptoskit_router::__private);
	let mut uses_navigation = false;
	let arms = routes.iter().map(|route| {
		let variant = format_ident!("{}", route.variant);
		let calls = std::iter::once(&route.page_call).chain(route.layouts.iter().rev());
		uses_navigation |= calls.clone().any(|call| {
			call.props
				.iter()
				.any(|prop| matches!(prop, Prop::Navigation { .. }))
		});
		let page_takes_route = route
			.page_call
			.props
			.iter()
			.any(|prop| matches!(prop, Prop::Route { .. }));
		let pattern = match &route.target {
			Target::Unit | Target::Struct { unit: true, .. } => quote!(Self::#variant),
			Target::Struct { .. } | Target::NotFound if page_takes_route => {
				quote!(Self::#variant(route))
			}
			Target::Struct { .. } | Target::NotFound => quote!(Self::#variant(_)),
		};
		// A unit struct route has no value in the variant, so the page gets
		// a fresh one.
		let page_route = if let Target::Struct {
			name, unit: true, ..
		} = &route.target
		{
			let name = format_ident!("{}", name);
			quote!(#name)
		} else {
			quote!(route)
		};
		let page = call(&route.page_call, |by_ref| {
			match (&route.target, by_ref) {
				(Target::Struct { unit: true, .. }, true) => quote!(&#page_route),
				(Target::Struct { unit: true, .. }, false) | (_, true) => quote!(#page_route),
				(_, false) => quote!(::core::clone::Clone::clone(#page_route)),
			}
		});
		let layouts = route.layouts.iter().rev().map(|layout| {
			call(layout, |by_ref| {
				if by_ref {
					quote!(self)
				} else {
					quote!(::core::clone::Clone::clone(self))
				}
			})
		});
		// Each call wraps the one before it; the outermost is the arm's value.
		let mut calls = std::iter::once(page).chain(layouts).collect::<Vec<_>>();
		let outermost = calls.pop().expect("every route has a page");
		quote! {
			#pattern => {
				#(let view = #private::IntoView::into_view(#calls);)*
				#private::IntoView::into_view(#outermost)
			}
		}
	});
	let arms = arms.collect::<Vec<_>>();
	let navigation = if uses_navigation {
		quote!(navigation)
	} else {
		quote!(_navigation)
	};
	quote! {
		impl ::leptoskit_router::Render for Route {
			fn render(&self, #navigation: &Navigation) -> #private::Element {
				match self {
					#(#arms)*
				}
			}
		}
	}
}

/// A call to a page or layout with an argument for each prop it declares.
/// `route` writes the route argument, by reference or by value.
fn call(call: &Call, route: impl Fn(bool) -> TokenStream) -> TokenStream {
	let private = quote!(::leptoskit_router::__private);
	let modules = call
		.modules
		.iter()
		.map(|module| format_ident!("{}", module));
	let function = format_ident!("{}", call.function);
	let arguments = call.props.iter().map(|prop| {
		match *prop {
			Prop::Route { by_ref } => route(by_ref),
			Prop::Navigation { by_ref: true } => quote!(navigation),
			Prop::Navigation { by_ref: false } => quote!(::core::clone::Clone::clone(navigation)),
			Prop::Children => quote!(#private::Fragment::new().with(view)),
		}
	});
	quote!(#(#modules)::*::#function(#(#arguments),*))
}
