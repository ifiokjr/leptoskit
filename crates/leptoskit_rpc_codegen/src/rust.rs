pub(crate) fn generate(context: &Context<'_>) -> Generated {
	let mut types = fresh_types(context, RUST_RESERVED_TYPES);
	let models = models_file(context, &mut types);
	let client = format!(
		"{}//! The transport: one method per published function.\n\n{}",
		context.banner("//"),
		client_file(context, &mut types, true)
	);
	Generated {
		files: vec![
			GeneratedFile::scaffold("Cargo.toml", cargo_toml(context)),
			GeneratedFile::scaffold(".gitignore", "/target\n"),
			GeneratedFile::code("src/models.rs", models),
			GeneratedFile::code("src/client.rs", client),
			GeneratedFile::code("src/live.rs", live_runtime(context)),
			GeneratedFile::code(
				"src/lib.rs",
				format!(
					"{}//! A typed client for the {} {} RPC.\n//!\n//! Generated by `leptoskit \
					 rpc generate --target rust`; see `client` for the calls, `models` for the \
					 types, and `live` for the live connection.\n\npub mod client;\n#[cfg(feature \
					 = \"live\")]\npub mod live;\npub mod models;\n\npub use client::Client;\npub \
					 use client::Error;\npub use client::FnErrorKind;\npub use models::*;\n",
					context.banner("//"),
					comment_text(&context.spec.title),
					comment_text(&context.spec.version)
				),
			),
			GeneratedFile::scaffold("README.md", readme(context)),
		],
	}
}

/// Tracks model names and the synthesized declarations for anonymous shapes.
///
/// Rendering is cached by hint and schema, so the same schema at the same
/// site — an argument in the client and in a generated CLI, say — always
/// synthesizes the same name, while two schemas that happen to share a hint
/// (an argument named `result` and the function's result) stay apart.
pub(crate) struct RustTypes {
	/// Every type name the models and the client's input structs share a
	/// namespace with.
	scope: Scope,
	/// The bound name of every component schema, by schema name.
	components: HashMap<String, String>,
	cache: HashMap<(String, String), String>,
	synthesized: Vec<String>,
}

/// A fresh type table with every component's name bound clear of
/// `reserved`; generators that share synthesized names (the Rust client and
/// the CLI over it) pass one instance between them.
pub(crate) fn fresh_types(context: &Context<'_>, reserved: &'static [&'static str]) -> RustTypes {
	let mut scope = Scope::new(reserved);
	let components = component_names(context.spec, &mut scope);
	RustTypes {
		scope,
		components,
		cache: HashMap::new(),
		synthesized: Vec::new(),
	}
}

/// The method name of every callable function, in order, clear of
/// `Client`'s own methods and of each other; the CLI calls them by these
/// names too.
pub(crate) fn method_names(context: &Context<'_>) -> Vec<String> {
	let mut scope = Scope::new(RUST_RESERVED_METHODS);
	context
		.functions()
		.map(|function| scope.bind(&rust_identifier(&function.name)))
		.collect()
}

/// The live connection's runtime: `live.rs` in the client, and in the copy
/// the CLI embeds.
pub(crate) fn live_runtime(context: &Context<'_>) -> String {
	format!(
		"{}{}",
		context.banner("//"),
		include_str!("templates/live.rs")
	)
}

/// The live methods next to the one-shot ones: `<function>_watch` for a
/// query, `<function>_live` for a mutation, and `join_<channel>` for a
/// channel, clear of `Client`'s own methods and of each other.
pub(crate) struct LiveMethods {
	/// The live method of every callable function, in order; `None` for a
	/// call or an action, which only run one-shot.
	pub(crate) functions: Vec<Option<String>>,
	/// The join method of every channel, in order.
	pub(crate) channels: Vec<String>,
}

pub(crate) fn live_methods(context: &Context<'_>) -> LiveMethods {
	let mut scope = Scope::new(RUST_RESERVED_METHODS);

	// Bound first, so the one-shot methods keep the names `method_names`
	// gives them.
	for function in context.functions() {
		scope.bind(&rust_identifier(&function.name));
	}

	let functions = context
		.functions()
		.map(|function| {
			let suffix = match function.kind {
				ApiKind::Query => "watch",
				ApiKind::Mutation => "live",
				_ => return None,
			};
			Some(scope.bind(&rust_identifier(&format!("{}_{suffix}", function.name))))
		})
		.collect();
	let channels = context
		.spec
		.channels
		.iter()
		.map(|channel| scope.bind(&rust_identifier(&format!("join_{}", channel.name))))
		.collect();
	LiveMethods {
		functions,
		channels,
	}
}

/// The parameter of every argument, in order, with no two alike.
fn parameter_names(function: &crate::spec::ApiFunction) -> Vec<String> {
	let mut scope = Scope::new(&[]);
	function
		.params
		.iter()
		.map(|param| scope.bind(&rust_identifier(&param.name)))
		.collect()
}

impl RustTypes {
	fn reserve(&mut self, wanted: &str) -> String {
		self.scope.bind(wanted)
	}

	/// A Rust type expression for `schema`, synthesizing structs and enums for
	/// anonymous shapes, named after `hint`.
	fn render(&mut self, schema: &Value, hint: &str, spec: &ApiSpec) -> String {
		let key = (hint.to_owned(), schema.to_string());

		if let Some(cached) = self.cache.get(&key) {
			return cached.clone();
		}

		let rendered = self.render_uncached(schema, hint, spec);
		self.cache.insert(key, rendered.clone());
		rendered
	}

	fn render_uncached(&mut self, schema: &Value, hint: &str, spec: &ApiSpec) -> String {
		let analyzed = analyze(schema);

		let base = match analyzed.shape {
			Shape::Ref(name) => {
				self.components
					.get(name)
					.cloned()
					.unwrap_or_else(|| "serde_json::Value".to_owned())
			}
			Shape::Null => "()".to_owned(),
			Shape::Boolean => "bool".to_owned(),
			Shape::Integer { format } => integer_type(format),
			Shape::Number { format } => {
				match format {
					Some("float") => "f32".to_owned(),
					_ => "f64".to_owned(),
				}
			}
			Shape::String {
				values: Some(_), ..
			} => self.render_string(schema, hint),
			Shape::String { .. } => "String".to_owned(),
			Shape::Array { items } => self.render_array(items, hint, spec),
			Shape::Tuple(items) => self.render_tuple(&items, hint, spec),
			Shape::Object(object) => self.render_object(schema, &object, hint, spec),
			Shape::Map { values } => self.render_map(values, hint, spec),
			Shape::Union(variants) => self.render_union(schema, &variants, hint, spec),
			Shape::Any => "serde_json::Value".to_owned(),
		};

		if analyzed.nullable && !base.starts_with("Option<") && base != "()" {
			format!("Option<{base}>")
		} else {
			base
		}
	}

	/// A string enum, declared and named.
	fn render_string(&mut self, schema: &Value, hint: &str) -> String {
		let name = self.reserve(&type_name(hint));
		self.synthesized.push(enum_declaration(schema, &name));
		name
	}

	/// A `Vec` of the item type.
	fn render_array(&mut self, items: Option<&Value>, hint: &str, spec: &ApiSpec) -> String {
		format!(
			"Vec<{}>",
			items.map_or_else(
				|| "serde_json::Value".to_owned(),
				|items| self.render(items, &format!("{hint}Item"), spec)
			)
		)
	}

	/// A tuple of the item types.
	fn render_tuple(&mut self, items: &[&Value], hint: &str, spec: &ApiSpec) -> String {
		let parts: Vec<String> = items
			.iter()
			.enumerate()
			.map(|(index, item)| self.render(item, &format!("{hint}{index}"), spec))
			.collect();
		format!("({},)", parts.join(", "))
	}

	/// A declared struct, or a map when the object has no properties.
	fn render_object(
		&mut self,
		schema: &Value,
		object: &ObjectShape<'_>,
		hint: &str,
		spec: &ApiSpec,
	) -> String {
		if object.properties.is_empty() {
			return match object.additional {
				Some(values) => {
					format!(
						"std::collections::HashMap<String, {}>",
						self.render(values, &format!("{hint}Value"), spec)
					)
				}
				None => "std::collections::HashMap<String, serde_json::Value>".to_owned(),
			};
		}

		let name = self.reserve(&type_name(hint));
		let declaration = struct_declaration(&name, description(schema), object, self, spec, &name);
		self.synthesized.push(declaration);
		name
	}

	/// A map of the value type.
	fn render_map(&mut self, values: Option<&Value>, hint: &str, spec: &ApiSpec) -> String {
		format!(
			"std::collections::HashMap<String, {}>",
			values.map_or_else(
				|| "serde_json::Value".to_owned(),
				|values| self.render(values, &format!("{hint}Value"), spec)
			)
		)
	}

	/// A union that names an enum, or `serde_json::Value` when it doesn't.
	fn render_union(
		&mut self,
		schema: &Value,
		variants: &[&Value],
		hint: &str,
		spec: &ApiSpec,
	) -> String {
		let name = self.reserve(&type_name(hint));
		let references: Vec<&Value> = variants.to_vec();
		let Some(serde_enum) = recognize_enum(&references) else {
			return "serde_json::Value".to_owned();
		};
		let declaration =
			serde_enum_declaration(&name, description(schema), &serde_enum, self, spec);
		self.synthesized.push(declaration);
		name
	}
}

/// Rust type for an integer schema format.
fn integer_type(format: Option<&str>) -> String {
	match format {
		Some("int8") => "i8".to_owned(),
		Some("int16") => "i16".to_owned(),
		Some("int32") => "i32".to_owned(),
		Some("uint8") => "u8".to_owned(),
		Some("uint16") => "u16".to_owned(),
		Some("uint32") => "u32".to_owned(),
		Some("uint64") => "u64".to_owned(),
		_ => "i64".to_owned(),
	}
}

/// One field of a generated struct.
struct Field {
	ident: String,
	type_name: String,
	wire: String,
	docs: Vec<String>,
	optional: bool,
}

/// Optional fields carry `Option<T>`, whether or not the schema was nullable,
/// so absence can be expressed for defaulted arguments too.
fn wrap_option(type_name: &str, optional: bool) -> String {
	if optional && !type_name.starts_with("Option<") {
		format!("Option<{type_name}>")
	} else {
		type_name.to_owned()
	}
}

fn field_attributes(field: &Field) -> String {
	let mut attributes = Vec::new();
	let rust_name = field.ident.trim_start_matches("r#");

	if rust_name != field.wire {
		attributes.push(format!("rename = {}", rust_string(&field.wire)));
	}

	if field.optional {
		attributes.push("default".to_owned());
		attributes.push("skip_serializing_if = \"Option::is_none\"".to_owned());
	}

	if attributes.is_empty() {
		String::new()
	} else {
		format!("\t#[serde({})]\n", attributes.join(", "))
	}
}

fn struct_declaration(
	name: &str,
	docs: Option<&str>,
	object: &ObjectShape<'_>,
	types: &mut RustTypes,
	spec: &ApiSpec,
	hint: &str,
) -> String {
	let mut fields = Vec::new();
	let mut field_names = Scope::new(&[]);

	for (wire, schema) in &object.properties {
		let field_type = types.render(schema, &format!("{hint}{}", type_name(wire)), spec);
		let optional = !object.is_required(wire) || has_default(schema);
		fields.push(Field {
			ident: field_names.bind(&rust_identifier(wire)),
			type_name: wrap_option(&field_type, optional),
			wire: (*wire).to_owned(),
			docs: description(schema)
				.map(|docs| docs.lines().map(str::trim).map(str::to_owned).collect())
				.unwrap_or_default(),
			optional,
		});
	}

	let mut out = String::new();

	for line in docs.unwrap_or_default().lines() {
		out.push_str(&format!("/// {line}\n"));
	}

	out.push_str("#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]\n");
	out.push_str(&format!("pub struct {name} {{\n"));

	for field in &fields {
		for line in &field.docs {
			out.push_str(&format!("\t/// {line}\n"));
		}

		out.push_str(&field_attributes(field));
		out.push_str(&format!("\tpub {}: {},\n", field.ident, field.type_name));
	}

	out.push_str("}\n\n");
	out
}

/// A plain enum for a string-enum schema.
fn enum_declaration(schema: &Value, name: &str) -> String {
	let values: Vec<&str> = match analyze(schema).shape {
		Shape::String {
			values: Some(values),
			..
		} => values,
		_ => Vec::new(),
	};

	let mut out = String::new();

	if let Some(docs) = description(schema) {
		for line in docs.lines() {
			out.push_str(&format!("/// {line}\n"));
		}
	}

	out.push_str(
		"#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize)]\n",
	);
	out.push_str(&format!("pub enum {name} {{\n"));
	let mut seen: HashSet<String> = HashSet::new();

	for value in &values {
		let variant = type_name(value);
		let mut variant = variant;
		let mut counter = 2;

		while !seen.insert(variant.clone()) {
			variant = format!("{}{counter}", type_name(value));
			counter += 1;
		}

		if variant.trim_start_matches("r#") != *value {
			out.push_str(&format!("\t#[serde(rename = {})]\n", rust_string(value)));
		}

		out.push_str(&format!("\t{variant},\n"));
	}

	out.push_str("}\n\n");
	out
}

/// The serde attributes and variants for a recognized enum shape.
fn serde_enum_declaration(
	name: &str,
	docs: Option<&str>,
	serde_enum: &SerdeEnum<'_>,
	types: &mut RustTypes,
	spec: &ApiSpec,
) -> String {
	let mut out = String::new();

	if let Some(docs) = docs {
		for line in docs.lines() {
			out.push_str(&format!("/// {line}\n"));
		}
	}

	out.push_str("#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]\n");

	match serde_enum {
		SerdeEnum::Internal { tag, .. } => {
			out.push_str(&format!("#[serde(tag = {})]\n", rust_string(tag)));
		}
		SerdeEnum::Adjacent { tag, content, .. } => {
			out.push_str(&format!(
				"#[serde(tag = {}, content = {})]\n",
				rust_string(tag),
				rust_string(content)
			));
		}
		SerdeEnum::External { .. } => {}
	}

	out.push_str(&format!("pub enum {name} {{\n"));

	let variants: &[EnumVariant<'_>] = match serde_enum {
		SerdeEnum::Internal { variants, .. }
		| SerdeEnum::Adjacent { variants, .. }
		| SerdeEnum::External { variants } => variants,
	};

	for variant in variants {
		match variant {
			EnumVariant::Unit { name } => {
				if type_name(name).trim_start_matches("r#") != *name {
					out.push_str(&format!("\t#[serde(rename = {})]\n", rust_string(name)));
				}

				out.push_str(&format!("\t{},\n", type_name(name)));
			}
			EnumVariant::Newtype { name, inner } => {
				if type_name(name).trim_start_matches("r#") != *name {
					out.push_str(&format!("\t#[serde(rename = {})]\n", rust_string(name)));
				}

				let inner_type = types.render(inner, &format!("{name}{}", type_name(name)), spec);
				out.push_str(&format!("\t{}({inner_type}),\n", type_name(name)));
			}
			EnumVariant::Struct { name, fields } => {
				if type_name(name).trim_start_matches("r#") != *name {
					out.push_str(&format!("\t#[serde(rename = {})]\n", rust_string(name)));
				}

				out.push_str(&format!("\t{} {{\n", type_name(name)));
				for (wire, schema) in &fields.properties {
					let field_type =
						types.render(schema, &format!("{name}{}", type_name(wire)), spec);
					let ident = rust_identifier(wire);
					let optional = !fields.is_required(wire) || has_default(schema);
					let field = Field {
						ident: ident.clone(),
						type_name: wrap_option(&field_type, optional),
						wire: (*wire).to_owned(),
						docs: Vec::new(),
						optional,
					};
					out.push_str(&field_attributes(&field));
					out.push_str(&format!("\t\t{ident}: {field_type},\n"));
				}

				out.push_str("\t},\n");
			}
		}
	}

	out.push_str("}\n\n");
	out
}

pub(crate) fn models_file(context: &Context<'_>, types: &mut RustTypes) -> String {
	let mut declarations = String::new();
	let mut aliases = String::new();

	for (schema_name, schema) in &context.spec.schemas {
		let name = types.components[schema_name].clone();
		let analyzed = analyze(schema);

		match (&analyzed.shape, analyzed.nullable) {
			(Shape::Object(object), false) if !object.properties.is_empty() => {
				declarations.push_str(&struct_declaration(
					&name,
					description(schema),
					object,
					types,
					context.spec,
					&name,
				));
			}

			(
				Shape::String {
					values: Some(_), ..
				},
				_,
			) => {
				declarations.push_str(&enum_declaration(schema, &name));
			}

			(Shape::Union(variants), _) if recognize_enum(variants).is_some() => {
				let references: Vec<&Value> = variants.clone();
				if let Some(serde_enum) = recognize_enum(&references) {
					declarations.push_str(&serde_enum_declaration(
						&name,
						description(schema),
						&serde_enum,
						types,
						context.spec,
					));
				}
			}

			_ => {
				let rendered = types.render(schema, &name, context.spec);
				if let Some(docs) = description(schema) {
					for line in docs.lines() {
						aliases.push_str(&format!("/// {line}\n"));
					}
				}

				aliases.push_str(&format!("pub type {name} = {rendered};\n\n"));
			}
		}
	}

	let mut out = context.banner("//");
	out.push_str(&format!(
		"//! Types for the {} {} RPC.\n\n#![allow(clippy::all)]\n\n",
		comment_text(&context.spec.title),
		comment_text(&context.spec.version)
	));

	for synthesized in &types.synthesized {
		out.push_str(synthesized);
	}

	out.push_str(&declarations);
	out.push_str(&aliases);
	out
}

/// The api module the CLI embeds: the models and the client behind one `mod`.
pub(crate) fn api_module(context: &Context<'_>, types: &mut RustTypes) -> String {
	let mut out = context.banner("//");
	out.push_str(
		"//! The generated client the CLI embeds.\n#![allow(dead_code)]\n\npub mod live;\npub mod \
		 models;\npub use models::*;\n\n",
	);
	// The CLI always speaks live, so it has no `live` feature to gate on.
	let client = client_file(context, types, false);
	for line in client.lines() {
		if line.trim() != LIVE_FEATURE {
			out.push_str(line);
			out.push('\n');
		}
	}
	out
}

/// The attribute that gates the client's live side behind its `live`
/// feature.
const LIVE_FEATURE: &str = "#[cfg(feature = \"live\")]";

/// The Rust types of a channel's join arguments, signal message, and
/// presence, shared by the client and the CLI.
pub(crate) fn channel_types(
	context: &Context<'_>,
	channel: &ApiChannel,
	types: &mut RustTypes,
) -> (String, String, String) {
	let hint = type_name(&channel.name);
	(
		types.render(&channel.args_schema, &format!("{hint}Args"), context.spec),
		types.render(
			&channel.message_schema,
			&format!("{hint}Message"),
			context.spec,
		),
		types.render(
			&channel.presence_schema,
			&format!("{hint}Presence"),
			context.spec,
		),
	)
}

/// One join argument of a channel, as the CLI takes it.
pub(crate) struct ChannelField {
	/// The wire name.
	pub(crate) wire: String,
	/// The Rust type, without an `Option` for absence.
	pub(crate) type_name: String,
	/// Whether the join needs it.
	pub(crate) required: bool,
	/// The field's doc comment.
	pub(crate) docs: String,
}

/// The join arguments of a channel in declaration order, when its argument
/// schema is an object (or names one); empty otherwise.
pub(crate) fn channel_fields(
	context: &Context<'_>,
	channel: &ApiChannel,
	types: &mut RustTypes,
) -> Vec<ChannelField> {
	// A named struct renders its fields with the struct's name as the hint,
	// so the same hint here finds the types the models declared.
	let (schema, hint) = match analyze(&channel.args_schema).shape {
		Shape::Ref(name) => {
			match (context.spec.schemas.get(name), types.components.get(name)) {
				(Some(schema), Some(bound)) => (schema, bound.clone()),
				_ => return Vec::new(),
			}
		}
		_ => {
			(
				&channel.args_schema,
				format!("{}Args", type_name(&channel.name)),
			)
		}
	};
	let Shape::Object(object) = analyze(schema).shape else {
		return Vec::new();
	};
	// Declaration order first, then anything the declaration didn't list.
	let mut wires: Vec<&str> = channel
		.fields
		.iter()
		.map(String::as_str)
		.filter(|wire| object.properties.iter().any(|(name, _)| name == wire))
		.collect();
	for (wire, _) in &object.properties {
		if !wires.contains(wire) {
			wires.push(*wire);
		}
	}
	wires
		.into_iter()
		.filter_map(|wire| {
			let (_, property) = object.properties.iter().find(|(name, _)| *name == wire)?;
			let rendered = types.render(
				property,
				&format!("{hint}{}", type_name(wire)),
				context.spec,
			);
			let required = object.is_required(wire) && !has_default(property);
			let type_name = if required {
				rendered
			} else {
				rendered
					.strip_prefix("Option<")
					.and_then(|inner| inner.strip_suffix('>'))
					.map_or(rendered.clone(), str::to_owned)
			};
			Some(ChannelField {
				wire: wire.to_owned(),
				type_name,
				required,
				docs: description(property).unwrap_or_default().to_owned(),
			})
		})
		.collect()
}

/// The Rust type of one function argument, shared by the client and the CLI.
pub(crate) fn param_type(
	context: &Context<'_>,
	function: &crate::spec::ApiFunction,
	param: &crate::spec::ApiParam,
	types: &mut RustTypes,
) -> String {
	let hint = type_name(&function.name);
	types.render(
		&param.schema,
		&format!("{hint}{}", type_name(&param.name)),
		context.spec,
	)
}

fn client_file(context: &Context<'_>, types: &mut RustTypes, models_import: bool) -> String {
	// One input struct per function that takes arguments, declared at module
	// level so the methods stay one-liners.
	let mut input_structs = String::new();
	let mut methods = String::new();
	let mut live = String::new();
	let live_names = live_methods(context);

	for ((function, method), live_method) in context
		.functions()
		.zip(method_names(context))
		.zip(live_names.functions)
	{
		let hint = type_name(&function.name);
		let mut fields: Vec<Field> = Vec::new();
		let mut arguments = Vec::new();

		for (param, identifier) in function.params.iter().zip(parameter_names(function)) {
			let param_type = types.render(
				&param.schema,
				&format!("{hint}{}", type_name(&param.name)),
				context.spec,
			);
			let param_type = wrap_option(&param_type, !param.is_required());
			arguments.push((identifier.clone(), param_type.clone()));
			fields.push(Field {
				ident: identifier,
				type_name: param_type,
				wire: param.name.clone(),
				docs: param.docs.lines().map(str::to_owned).collect(),
				optional: !param.is_required(),
			});
		}

		let output = types.render(
			&function.output_schema,
			&format!("{hint}Result"),
			context.spec,
		);
		let void = output == "()";
		// Declared next to the glob-imported models, so bound with them.
		let input_struct = if fields.is_empty() {
			String::new()
		} else {
			types.reserve(&format!("{hint}Input"))
		};

		if !fields.is_empty() {
			input_structs.push_str("#[derive(Serialize)]\n");
			input_structs.push_str(&format!("struct {input_struct} {{\n"));

			for field in &fields {
				for line in &field.docs {
					input_structs.push_str(&format!("\t/// {line}\n"));
				}

				input_structs.push_str(&field_attributes(field));
				input_structs.push_str(&format!("\t{}: {},\n", field.ident, field.type_name));
			}

			input_structs.push_str("}\n\n");
		}

		// The docs the one-shot method and its live form share.
		let docs = function_docs(function, &fields);
		methods.push_str(&docs);

		if function.kind.is_idempotent_with_key() {
			if !function.docs.is_empty()
				|| function.params.iter().any(|param| !param.docs.is_empty())
			{
				methods.push_str("\t///\n");
			}
			methods.push_str(
				"\t/// Call it on [`Client::with_idempotency_key`] to make a retried call run \
				 once.\n",
			);
		}

		if function.deprecated {
			methods.push_str("\t#[deprecated]\n");
		}
		let signature = if arguments.is_empty() {
			format!("\tpub async fn {method}(&self)")
		} else {
			format!(
				"\tpub async fn {method}(&self, {})",
				arguments
					.iter()
					.map(|(identifier, param_type)| format!("{identifier}: {param_type}"))
					.collect::<Vec<_>>()
					.join(", ")
			)
		};

		let encoding = match function.input {
			crate::spec::HttpInput::Query => "Encoding::Query",
			crate::spec::HttpInput::Form => "Encoding::Form",
			crate::spec::HttpInput::Json | crate::spec::HttpInput::Other { .. } => "Encoding::Json",
		};
		let payload = if fields.is_empty() {
			"&serde_json::json!({})".to_owned()
		} else {
			format!(
				"&{input_struct} {{ {} }}",
				arguments
					.iter()
					.map(|(identifier, _)| identifier.clone())
					.collect::<Vec<_>>()
					.join(", ")
			)
		};

		let call = format!(
			"self.{}({}, {}, {}, {payload})",
			if void { "call_void" } else { "call" },
			rust_string(&function.method),
			rust_string(&function.path),
			encoding
		);

		if void {
			methods.push_str(&format!(
				"{signature} -> Result<(), Error> {{\n\t\t{call}.await\n\t}}\n\n"
			));
		} else {
			methods.push_str(&format!(
				"{signature} -> Result<{output}, Error> {{\n\t\t{call}.await\n\t}}\n\n"
			));
		}

		if let Some(live_method) = live_method {
			live.push_str(&live_function(
				function,
				&live_method,
				&docs,
				&arguments,
				&output,
				&payload,
			));
		}
	}

	for (channel, method) in context.spec.channels.iter().zip(live_names.channels) {
		live.push_str(&live_channel(context, channel, &method, types));
	}

	client_module(context, models_import, &input_structs, &methods, &live)
}

/// A function's docs and its arguments', as the one-shot method and its live
/// form share them.
fn function_docs(function: &crate::spec::ApiFunction, fields: &[Field]) -> String {
	let mut docs = String::new();

	for line in function.docs.lines() {
		docs.push_str(&format!("\t/// {line}\n"));
	}

	let documented: Vec<(&crate::spec::ApiParam, &Field)> = function
		.params
		.iter()
		.zip(fields)
		.filter(|(param, _)| !param.docs.is_empty())
		.collect();

	if !documented.is_empty() {
		if !function.docs.is_empty() {
			docs.push_str("\t///\n");
		}

		docs.push_str("\t/// # Arguments\n\t///\n");

		for (param, field) in documented {
			docs.push_str(&format!(
				"\t/// * `{}` — {}\n",
				field.ident,
				param.docs.trim()
			));
		}
	}

	docs
}

/// The client module: its imports and constants, the input structs, the
/// runtime, and the one-shot and live methods.
fn client_module(
	context: &Context<'_>,
	models_import: bool,
	input_structs: &str,
	methods: &str,
	live: &str,
) -> String {
	format!(
		"{models_use}use serde::Serialize;\nuse serde::de::DeserializeOwned;\n\n/// The server \
		 origin baked in at generation time.\npub const DEFAULT_SERVER_URL: &str = \
		 {server_url};\n\n/// Where the server serves the live connection, relative to its \
		 origin.\npub const LIVE_PATH: &str = {live_path};\n\n{input_structs}{runtime}\nimpl \
		 Client {{\n{methods}}}\n\n{LIVE_FEATURE}\nimpl Client \
		 {{\n{LIVE_RUNTIME}{live_key}\n{live}}}\n",
		live_key = if context
			.functions()
			.any(|function| function.kind == ApiKind::Mutation)
		{
			LIVE_KEY
		} else {
			""
		},
		models_use = if models_import {
			"use crate::models::*;\n#[cfg(feature = \"live\")]\nuse crate::live;\n"
		} else {
			""
		},
		runtime = RUNTIME,
		server_url = rust_string(
			context
				.server_url
				.as_deref()
				.unwrap_or("https://example.com")
		),
		live_path = rust_string(&context.spec.live_path),
	)
}

/// A query's `_watch` or a mutation's `_live` method: the one-shot method's
/// docs and arguments, over the live connection.
fn live_function(
	function: &crate::spec::ApiFunction,
	method: &str,
	docs: &str,
	arguments: &[(String, String)],
	output: &str,
	payload: &str,
) -> String {
	let mut out = docs.to_owned();

	if !docs.is_empty() {
		out.push_str("\t///\n");
	}

	let parameters = arguments
		.iter()
		.map(|(identifier, param_type)| format!(", {identifier}: {param_type}"))
		.collect::<Vec<_>>()
		.concat();
	let name = rust_string(&function.name);
	let deprecated = if function.deprecated {
		"\t#[deprecated]\n"
	} else {
		""
	};

	if function.kind == ApiKind::Query {
		out.push_str(&format!(
			"\t/// Watches this query over the live connection: the subscription yields its first \
			 value\n\t/// and each new one, and unsubscribes when dropped.\n{deprecated}\tpub fn \
			 {method}(&self{parameters}) -> live::Subscription<{output}> \
			 {{\n\t\tself.live().subscribe({name}, {payload})\n\t}}\n\n"
		));
	} else {
		out.push_str(&format!(
			"\t/// Runs this mutation over the live connection. It returns once this \
			 client's\n\t/// subscriptions show the write, and a call whose answer is lost is \
			 sent again after\n\t/// a reconnect with the same key, so it runs once; call it \
			 on\n\t/// [`Client::with_idempotency_key`] to choose the key.\n{deprecated}\tpub \
			 async fn {method}(&self{parameters}) -> Result<{output}, live::LiveError> \
			 {{\n\t\tself.live().mutate({name}, {payload}, self.live_key()).await\n\t}}\n\n"
		));
	}

	out
}

/// A channel's `join_` method.
fn live_channel(
	context: &Context<'_>,
	channel: &ApiChannel,
	method: &str,
	types: &mut RustTypes,
) -> String {
	let (args, message, presence) = channel_types(context, channel, types);
	let mut out = String::new();

	for line in channel.docs.lines() {
		out.push_str(&format!("\t/// {}\n", comment_text(line.trim_end())));
	}

	if !channel.docs.is_empty() {
		out.push_str("\t///\n");
	}

	out.push_str(&format!(
		"\t/// Joins the channel over the live connection. `presence` is what this connection \
		 shows the\n\t/// others, or the channel's default when `None`. The channel yields \
		 signals and presence,\n\t/// is joined again after a reconnect, and is left when \
		 dropped.\n{deprecated}\tpub fn {method}(&self, args: {args}, presence: \
		 Option<{presence}>) -> live::Channel<{message}, {presence}> \
		 {{\n\t\tself.live().join({name}, &[{fields}], &args, presence.as_ref())\n\t}}\n\n",
		deprecated = if channel.deprecated {
			"\t#[deprecated]\n"
		} else {
			""
		},
		name = rust_string(&channel.name),
		fields = channel
			.fields
			.iter()
			.map(|field| rust_string(field))
			.collect::<Vec<_>>()
			.join(", "),
	));
	out
}

