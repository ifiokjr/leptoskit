//! The Rust client crate: typed models and a `reqwest` transport.
//!
//! Models come from the schemas with serde derives that reproduce the
//! original wire shapes — string enums, internally/adjacently/externally
//! tagged enums, `Option` for nullable, `#[serde(default)]` for defaulted —
//! and anything the generator cannot model falls back to `serde_json::Value`.
//! The crate depends on neither leptos nor `leptoskit_rpc`: a consumer needs
//! only an async runtime.

// Generators build source text; the allocation `write!` would save is noise here.
#![allow(clippy::format_push_string)]

