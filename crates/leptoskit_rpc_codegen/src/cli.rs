//! The CLI client: one command per published function.
//!
//! The crate embeds the generated Rust client (same models, same transport)
//! behind a clap command line: every function becomes a kebab-case command,
//! every argument a `--flag` parsed as JSON into the function's own type, and
//! the doc comments become `--help` text. The result prints as pretty JSON.

// Generators build source text; the allocation `write!` would save is noise here.
#![allow(clippy::format_push_string)]

use crate::generate::Context;
use crate::generate::Generated;
use crate::generate::GeneratedFile;
use crate::naming::RUST_CLI_RESERVED_ARGUMENTS;
use crate::naming::RUST_CLI_RESERVED_TYPES;
use crate::naming::Scope;
use crate::naming::comment_text;
use crate::naming::kebab;
use crate::naming::rust_identifier;
use crate::naming::rust_string;
use crate::naming::toml_string;
use crate::naming::type_name;
use crate::spec::ApiFunction;
use crate::spec::ApiParam;

pub(crate) fn generate(context: &Context<'_>) -> Generated {
	let mut types = crate::rust::fresh_types(context, RUST_CLI_RESERVED_TYPES);
	let models = crate::rust::models_file(context, &mut types);
	let api = crate::rust::api_module(context, &mut types);
	let mut out = context.banner("//");
	out.push_str(&format!(
		"//! The {title} {version} RPC, as a command line.\n//!\n//! Generated by `leptoskit rpc \
		 generate --target cli`; run with --help for every command.\n\n#[cfg(target_arch = \
		 \"wasm32\")]\ncompile_error!(\"the CLI runs on native targets\");\n\nmod api;\n\nuse \
		 api::*;\nuse clap::Parser;\nuse clap::Subcommand;\nuse serde::de::DeserializeOwned;\n\n/// A typed \
		 client for the {title} RPC.\n#[derive(Debug, Parser)]\n#[command(\n\tname = \
		 {command_name},\n\tversion,\n\tabout = {about},\n)]\nstruct Cli {{\n\t/// The origin the \
		 RPC is served from, such as https://api.example.com.\n\t#[arg(long, global = true)]\n\t\
		 server_url: Option<String>,\n\n\t#[command(subcommand)]\n\tcommand: Command,\n}}\n\n/// \
		 One command per published function.\n#[derive(Debug, Subcommand)]\nenum Command {{\n",
		title = comment_text(&context.spec.title),
		version = comment_text(&context.spec.version),
		command_name = rust_string(&kebab(&context.options.package_name)),
		about = rust_string(&format!(
			"A command line for the {} RPC. Every command calls the server function of the same \
			 name; run a command with --help for its arguments.",
			context.spec.title
		)),
	));

	for (function, variant) in context.functions().zip(variant_names(context)) {
		let arguments = argument_names(function);
		let mut docs: Vec<String> = if function.docs.is_empty() {
			vec![format!("Runs {}.", function.name)]
		} else {
			function
				.docs
				.lines()
				.map(str::trim)
				.map(str::to_owned)
				.collect()
		};
		let documented: Vec<(&ApiParam, &String)> = function
			.params
			.iter()
			.zip(&arguments)
			.filter(|(param, _)| !param.docs.is_empty())
			.collect();
		for (param, argument) in documented {
			docs.push(String::new());
			docs.push(format!("[{argument}] {}", param.docs.trim()));
		}
		if function.deprecated {
			docs.push(String::new());
			docs.push("Deprecated.".to_owned());
		}
		for line in docs.iter().flat_map(|text| text.split('\n')) {
			out.push_str(&format!("\t/// {}\n", comment_text(line)));
		}
		out.push_str(&format!(
			"\t#[command(name = {})]\n",
			rust_string(&kebab(&function.name))
		));
		out.push_str(&format!("\t{variant} {{\n"));
		for (param, ident) in function.params.iter().zip(&arguments) {
			for line in param.docs.lines() {
				out.push_str(&format!("\t\t/// {line}\n"));
			}
			let raw_type = crate::rust::param_type(context, function, param, &mut types);
			// A `Json<T>` newtype keeps clap from applying its own `Vec` and
			// `Option` magic: every `--flag` takes one JSON value, parsed into
			// the function's own type.
			// The clap `Option` already models absence, so the `Json` wraps
			// the type without its own `Option` layer.
			let field_type = if param.is_required() {
				format!("Json<{raw_type}>")
			} else {
				let inner = raw_type
					.strip_prefix("Option<")
					.and_then(|wrapped| wrapped.strip_suffix('>'))
					.unwrap_or(&raw_type);
				format!("Option<Json<{inner}>>")
			};
			out.push_str(&format!("\t\t#[arg(long)]\n\t\t{ident}: {field_type},\n"));
		}
		if function.kind.is_idempotent_with_key() {
			out.push_str(
				"\t\t/// Any unique string. Running the command again with the same key and \
				 arguments\n\t\t/// prints the first run's result instead of running it \
				 twice.\n\t\t#[arg(long)]\n\t\tidempotency_key: Option<String>,\n",
			);
		}
		out.push_str("\t},\n");
	}
	out.push_str("}\n\n");

	out.push_str(&main_source(context));

	Generated {
		files: vec![
			GeneratedFile::scaffold("Cargo.toml", cargo_toml(context)),
			GeneratedFile::scaffold(".gitignore", "/target\n"),
			GeneratedFile::code("src/api/mod.rs", api),
			GeneratedFile::code("src/api/models.rs", models),
			GeneratedFile::code("src/main.rs", out),
			GeneratedFile::scaffold("README.md", readme(context)),
		],
	}
}

/// The `Command` variant of every callable function, in order, with no two
/// alike.
fn variant_names(context: &Context<'_>) -> Vec<String> {
	let mut scope = Scope::new(&[]);
	context
		.functions()
		.map(|function| scope.bind(&type_name(&function.name)))
		.collect()
}

/// The field, and so the `--flag`, of every argument, in order, clear of the
/// flags clap and the CLI define themselves.
fn argument_names(function: &ApiFunction) -> Vec<String> {
	let mut scope = Scope::new(RUST_CLI_RESERVED_ARGUMENTS);
	function
		.params
		.iter()
		.map(|param| scope.bind(&rust_identifier(&param.name)))
		.collect()
}

/// The `--flag` clap derives from an argument's field.
fn flag(argument: &str) -> String {
	kebab(argument.trim_start_matches("r#"))
}

/// The `main` that dispatches commands to the client.
fn main_source(context: &Context<'_>) -> String {
	let mut arms = String::new();
	let calls = context
		.functions()
		.zip(variant_names(context))
		.zip(crate::rust::method_names(context));
	for ((function, variant), method) in calls {
		let arguments = argument_names(function);
		let mut fields = Vec::new();
		for (param, ident) in function.params.iter().zip(&arguments) {
			if param.is_required() {
				fields.push(format!("{ident}.0"));
			} else {
				fields.push(format!("{ident}.map(|json| json.0)"));
			}
		}
		let argument_list = fields.join(", ");
		if function.kind.is_idempotent_with_key() {
			let mut bindings = arguments.clone();
			bindings.push("idempotency_key".to_owned());
			arms.push_str(&format!(
				"\t\tCommand::{variant} {{ {} }} => match keyed(&api, idempotency_key) \
				 {{\n\t\t\tOk(api) => \
				 run(api.{method}({argument_list}).await).await,\n\t\t\tErr(error) => \
				 Err(error),\n\t\t}},\n",
				bindings.join(", "),
			));
		} else {
			arms.push_str(&format!(
				"\t\tCommand::{variant} {{ {} }} => \
				 run(api.{method}({argument_list}).await).await,\n",
				arguments.join(", "),
			));
		}
	}
	let keyed = if context
		.functions()
		.any(|function| function.kind.is_idempotent_with_key())
	{
		"\n/// The client, sending `key` as the `Idempotency-Key` when there is one.\nfn \
		 keyed(api: &api::Client, key: Option<String>) -> Result<api::Client, String> {\n\tmatch \
		 key {\n\t\tSome(key) => reqwest::header::HeaderValue::from_str(&key)\n\t\t\t.map(|key| \
		 api.with_idempotency_key(key))\n\t\t\t.map_err(|_| \"--idempotency-key must be printable \
		 ASCII\".to_owned()),\n\t\tNone => Ok(api.clone()),\n\t}\n}\n"
	} else {
		""
	};
	format!(
		"fn main() {{\n\tlet cli = Cli::parse();\n\tlet runtime = \
		 tokio::runtime::Builder::new_current_thread()\n\t\t.enable_all()\n\t\t.build()\n\t\t.\
		 expect(\"the CLI's async runtime\");\n\truntime.block_on(async move {{\n\t\tlet api = \
		 match cli.server_url {{\n\t\t\tSome(server_url) => \
		 api::Client::with_server_url(server_url),\n\t\t\tNone => \
		 api::Client::new(),\n\t\t}};\n\t\tlet outcome: Result<String, String> = match \
		 cli.command {{\n{arms}\t\t}};\n\t\tmatch outcome {{\n\t\t\tOk(output) => \
		 println!(\"{{output}}\"),\n\t\t\tErr(error) => {{\n\t\t\t\teprintln!(\"error: \
		 {{error}}\");\n\t\t\t\tstd::process::exit(1);\n\t\t\t}}\n\t\t}}\n\t}});\n}}\n\n/// Runs \
		 one call and prints its result as pretty JSON.\nasync fn run<T: \
		 serde::Serialize>(outcome: Result<T, api::Error>) -> Result<String, String> {{\n\tlet \
		 value = outcome.map_err(|error| \
		 error.to_string())?;\n\tserde_json::to_string_pretty(&value).map_err(|error| \
		 error.to_string())\n}}\n\n/// A `--flag` value parsed as JSON into the function's own \
		 type, so enums and structs validate before anything is sent.\n#[derive(Clone)]\nstruct \
		 Json<T>(T);\n\nimpl<T: DeserializeOwned> std::str::FromStr for Json<T> {{\n\ttype Err = \
		 String;\n\n\tfn from_str(text: &str) -> Result<Self, Self::Err> \
		 {{\n\t\tserde_json::from_str(text)\n\t\t\t.map(Json)\n\t\t\t.map_err(|error| \
		 format!(\"not valid JSON for this argument: {{error}}\"))\n\t}}\n}}\n\nimpl<T: \
		 serde::Serialize> std::fmt::Debug for Json<T> {{\n\tfn fmt(&self, formatter: &mut \
		 std::fmt::Formatter<'_>) -> std::fmt::Result {{\n\t\twrite!(formatter, \"{{}}\", \
		 serde_json::to_string(&self.0).expect(\"serializable\"))\n\t}}\n}}\n{keyed}",
	)
}

fn cargo_toml(context: &Context<'_>) -> String {
	format!(
		"{banner}# The CLI is its own workspace so it builds from any directory. To share the
# app's target directory and lockfile instead, delete this table and add the
# crate to the app workspace's `members`.
[workspace]

[package]
name = {name}
version = {version}
edition = \"2021\"
publish = false
description = {description}

[dependencies]
clap = {{ version = \"4\", features = [\"derive\"] }}
reqwest = {{ version = \"0.12\", default-features = false, features = [\"json\", \"rustls-tls\"] }}
serde = {{ version = \"1\", features = [\"derive\"] }}
serde_json = \"1\"
serde_qs = \"0.15\"
thiserror = \"2\"
tokio = {{ version = \"1\", features = [\"rt\"] }}
",
		banner = context.banner("#"),
		name = toml_string(&context.options.package_name),
		version = toml_string(&context.version),
		description = toml_string(&format!(
			"A command line for the {} RPC.",
			context.spec.title
		)),
	)
}

fn readme(context: &Context<'_>) -> String {
	let example = context
		.functions()
		.next()
		.map_or_else(String::new, |function| {
			let args: Vec<String> = function
				.params
				.iter()
				.zip(argument_names(function))
				.map(|(param, argument)| {
					if param.is_required() {
						format!("--{} '<json>'", flag(&argument))
					} else {
						format!("[--{} '<json>']", flag(&argument))
					}
				})
				.collect();
			format!(
				"{command} {subcommand} {args}\n",
				command = kebab(&context.options.package_name),
				subcommand = kebab(&function.name),
				args = args.join(" ")
			)
		});
	let commands: Vec<String> = context
		.functions()
		.map(|function| {
			format!(
				"- `{}` — {}",
				kebab(&function.name),
				function.docs.lines().next().unwrap_or_default().trim()
			)
		})
		.collect();
	format!(
		"# {name}

A command line for the **{title} {version}** RPC, generated by `leptoskit rpc generate \
--target cli`.

Every published function is a command with the same name in kebab-case; every argument is a \
`--flag` parsed as JSON into the function's own type, so enums and structs validate before \
anything is sent. Results print as pretty JSON.

## Usage

```bash
{example}```

Pass `--server-url https://api.example.com` to point it at a server.

## Commands

{commands}
",
		name = context.options.package_name,
		commands = commands.join("\n"),
		title = context.spec.title,
		version = context.spec.version,
	)
}
