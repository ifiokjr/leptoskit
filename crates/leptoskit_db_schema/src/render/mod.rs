//! Turns a [`Plan`] into SQL for its dialect.

mod postgres;
mod sqlite;

use std::collections::HashMap;
use std::fmt::Write;

use crate::Dialect;
use crate::Plan;
use crate::Risk;
use crate::Schema;
use crate::Step;
use crate::TableName;

/// The first line of every generated migration.
pub const GENERATED_HEADER: &str = "-- @generated by leptoskit db. Edits are allowed: the \
                                    migration is applied as written, and schema.json beside it \
                                    records the schema it produces.";

/// The comment that tells the migrator to turn SQLite's foreign key
/// enforcement off while this migration runs, and to check every foreign key
/// before it commits. Table rebuilds need it.
pub const FOREIGN_KEYS_OFF_DIRECTIVE: &str = "-- leptoskit: foreign-keys-off";

/// One migration's SQL, ready to write to `migration.sql`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Migration {
	/// The dialect the statements are written for.
	pub dialect: Dialect,
	/// The statements, in order, without trailing semicolons.
	pub statements: Vec<String>,
	/// SQLite only: whether foreign key enforcement must be off while the
	/// migration runs, because it rebuilds tables.
	pub foreign_keys_off: bool,
	/// What the reader should know: the risk of each step, and anything the
	/// database won't enforce.
	pub notes: Vec<String>,
}

impl Migration {
	/// The full `migration.sql`: a header, the notes as comments, then each
	/// statement followed by `;`.
	pub fn sql(&self) -> String {
		let mut sql = String::new();
		let _ = writeln!(sql, "{GENERATED_HEADER}");
		let _ = writeln!(sql, "-- dialect: {}", self.dialect);

		if self.foreign_keys_off {
			let _ = writeln!(sql, "{FOREIGN_KEYS_OFF_DIRECTIVE}");
		}

		if !self.notes.is_empty() {
			sql.push_str("--\n");

			for note in &self.notes {
				let _ = writeln!(sql, "-- {note}");
			}
		}

		for statement in &self.statements {
			sql.push('\n');
			sql.push_str(statement);
			sql.push_str(";\n");
		}

		sql
	}
}

/// Renders `plan`, which turns `previous` into `target`, as SQL.
///
/// Both schemas are needed: SQLite can't alter most of a table in place, so
/// some steps rebuild the table from its new definition and copy the rows
/// across.
pub fn render(plan: &Plan, previous: &Schema, target: &Schema) -> Migration {
	let mut migration = match plan.dialect {
		Dialect::Postgres => postgres::render(plan, previous, target),
		Dialect::Sqlite => sqlite::render(plan, previous, target),
	};

	let mut risks: Vec<String> = plan
		.steps
		.iter()
		.filter_map(|step| {
			match step.risk() {
				Risk::Safe => None,
				Risk::MayFail(reason) => Some(format!("may fail: {reason}")),
				Risk::LosesData(reason) => Some(format!("loses data: {reason}")),
			}
		})
		.collect();
	risks.append(&mut migration.notes);
	migration.notes = risks;
	migration
}

/// Every table's name before this plan's renames, by its new name. Steps
/// that run before the renames have to use the old names.
fn names_before_renames(plan: &Plan) -> HashMap<TableName, TableName> {
	plan.steps
		.iter()
		.filter_map(|step| {
			match step {
				Step::RenameTable { from, to } => Some((to.clone(), from.clone())),
				_ => None,
			}
		})
		.collect()
}

/// Formats a check bound: whole numbers as integers, so that integer columns
/// compare with integers.
fn number_literal(value: f64) -> String {
	if value.fract() == 0.0 && value.abs() < 9_007_199_254_740_992.0 {
		format!("{}", value as i64)
	} else {
		float_literal(value)
	}
}

/// Formats a float default so that it always reads as a float.
fn float_literal(value: f64) -> String {
	let text = value.to_string();

	if text.contains(['.', 'e', 'E']) {
		text
	} else {
		format!("{text}.0")
	}
}
