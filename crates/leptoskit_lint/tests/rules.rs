#[test]
fn files_named_directly_share_their_project_configuration() {
	let project = tempfile::tempdir().expect("scratch project");
	std::fs::write(
		project.path().join("leptoskit.toml"),
		"[lint.rules]\nmarkup_style = \"deny\"\n",
	)
	.expect("write config");
	let first = project.path().join("first.rs");
	let second = project.path().join("second.rs");
	std::fs::write(&first, BUILDER_TREE).expect("write source");
	std::fs::write(&second, BUILDER_TREE).expect("write source");
	let report = lint_paths(&[first, second]).expect("lint");
	assert_eq!(report.files, 2);
	assert_eq!(report.errors(), 2);
}

#[test]
fn a_missing_path_fails_the_run() {
	let project = tempfile::tempdir().expect("scratch project");
	let missing = project.path().join("missing");
	let error = lint_paths(std::slice::from_ref(&missing)).expect_err("missing path");
	assert!(
		error.to_string().contains(&missing.display().to_string()),
		"{error}"
	);
}

#[test]
fn an_invalid_exclude_pattern_fails_the_run() {
	let project = tempfile::tempdir().expect("scratch project");
	std::fs::write(
		project.path().join("leptoskit.toml"),
		"[lint]\nexclude = [\"src/[\"]\n",
	)
	.expect("write config");
	std::fs::write(project.path().join("lib.rs"), "").expect("write source");
	let error = lint_paths(&[project.path().to_owned()]).expect_err("invalid glob");
	assert!(error.to_string().contains("src/["), "{error}");
}

/// Permissions decide these, and a superuser reads everything, so each
/// checks that the file really is unreadable before it expects an error.
#[cfg(unix)]
mod unreadable {
	use std::os::unix::fs::PermissionsExt as _;
	use std::path::Path;

	use leptoskit_lint::lint_paths;

	fn lock(path: &Path) -> bool {
		std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o000)).expect("chmod");
		std::fs::read_dir(path).is_err() && std::fs::read(path).is_err()
	}

	#[test]
	fn an_unreadable_source_fails_the_run() {
		let project = tempfile::tempdir().expect("scratch project");
		let source = project.path().join("lib.rs");
		std::fs::write(&source, "").expect("write source");
		if !lock(&source) {
			return;
		}
		let error = lint_paths(&[project.path().to_owned()]).expect_err("unreadable source");
		assert!(error.to_string().contains("lib.rs"), "{error}");
	}

	#[test]
	fn an_unreadable_configuration_fails_the_run() {
		let project = tempfile::tempdir().expect("scratch project");
		let config = project.path().join("leptoskit.toml");
		std::fs::write(&config, "").expect("write config");
		std::fs::write(project.path().join("lib.rs"), "").expect("write source");
		if !lock(&config) {
			return;
		}
		let error = lint_paths(&[project.path().to_owned()]).expect_err("unreadable config");
		assert!(error.to_string().contains("leptoskit.toml"), "{error}");
	}

	#[test]
	fn an_unreadable_directory_fails_the_run() {
		let project = tempfile::tempdir().expect("scratch project");
		let hidden = project.path().join("locked");
		std::fs::create_dir(&hidden).expect("create directory");
		let locked = lock(&hidden);
		let result = lint_paths(&[project.path().to_owned()]);
		// Restore access so the scratch directory can be removed.
		std::fs::set_permissions(&hidden, std::fs::Permissions::from_mode(0o755)).expect("chmod");
		if locked {
			let error = result.expect_err("unreadable directory");
			assert!(error.to_string().contains("locked"), "{error}");
		}
	}
}

#[test]
fn errors_render_in_red_with_paths_outside_the_base_shown_whole() {
	let report = lint(
		Some("[lint.rules]\nmarkup_style = \"deny\"\n"),
		"fn screen() -> Element {\n\tView().child(Text(\"Hi\"))\n}\n",
	);
	let diagnostic = &report.diagnostics[0];
	let elsewhere = tempfile::tempdir().expect("unrelated base");
	let rendered = render_diagnostic(diagnostic, elsewhere.path());
	let plain = anstream::adapter::strip_str(&rendered).to_string();
	assert!(
		plain.starts_with("error[leptoskit::markup_style]"),
		"{plain}"
	);
	assert!(
		plain.contains(&diagnostic.path.display().to_string()),
		"{plain}"
	);
}

#[test]
fn findings_that_span_lines_underline_their_first_character() {
	let report = lint(
		None,
		"fn screen() -> Element {\n\tView().child(Text(\"Hi\"))\n}\n",
	);
	// The rules underline names, which sit on one line; a caller's finding
	// may cover more.
	let mut diagnostic = report.diagnostics[0].clone();
	diagnostic.finding.end.line += 2;
	let diagnostic = &diagnostic;
	let base = diagnostic
		.path
		.parent()
		.and_then(Path::parent)
		.expect("project root");
	let rendered = render_diagnostic(diagnostic, base);
	let plain = anstream::adapter::strip_str(&rendered).to_string();
	insta::assert_snapshot!(plain);
}
