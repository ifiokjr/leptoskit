//! The rules over small projects written to a scratch directory.

use std::path::Path;

use leptoskit_lint::LintLevel;
use leptoskit_lint::Report;
use leptoskit_lint::Rule;
use leptoskit_lint::lint_paths;
use leptoskit_lint::render_diagnostic;

/// Lints `source` as `src/lib.rs` of a project with `config` as its
/// `leptoskit.toml`, or no configuration at all.
fn lint(config: Option<&str>, source: &str) -> Report {
	let project = tempfile::tempdir().expect("scratch project");
	if let Some(config) = config {
		std::fs::write(project.path().join("leptoskit.toml"), config).expect("write config");
	}
	std::fs::create_dir(project.path().join("src")).expect("create src");
	std::fs::write(project.path().join("src/lib.rs"), source).expect("write source");
	lint_paths(&[project.path().to_owned()]).expect("lint")
}

fn rules(report: &Report) -> Vec<(Rule, usize)> {
	report
		.diagnostics
		.iter()
		.map(|diagnostic| (diagnostic.finding.rule, diagnostic.finding.start.line))
		.collect()
}

const BUILDER_TREE: &str = r#"
fn screen() -> Element {
	View()
		.class("p-4")
		.child(Text("Hello"))
		.child(Button("Go"))
}
"#;

const MARKUP_TREE: &str = r#"
fn screen() -> Element {
	view! { <View class="p-4"><Text>"Hello"</Text></View> }
}
"#;

#[test]
fn builder_trees_are_reported_once_at_their_root_by_default() {
	let report = lint(None, BUILDER_TREE);
	assert_eq!(rules(&report), [(Rule::MarkupStyle, 3)]);
	assert_eq!(report.warnings(), 1);
	assert!(!report.failed(false));
	assert!(report.failed(true));
}

#[test]
fn markup_passes_by_default() {
	assert_eq!(rules(&lint(None, MARKUP_TREE)), []);
}

#[test]
fn builder_projects_report_markup_instead() {
	let config = "[lint]\nmarkup = \"builder\"\n";
	assert_eq!(rules(&lint(Some(config), BUILDER_TREE)), []);
	assert_eq!(
		rules(&lint(Some(config), MARKUP_TREE)),
		[(Rule::MarkupStyle, 3)]
	);
}

#[test]
fn any_markup_allows_both() {
	let config = "[lint]\nmarkup = \"any\"\n";
	assert_eq!(rules(&lint(Some(config), BUILDER_TREE)), []);
	assert_eq!(rules(&lint(Some(config), MARKUP_TREE)), []);
}

#[test]
fn components_declared_in_the_project_count_as_builder_roots() {
	let source = r#"
#[component]
fn Card(title: String) -> impl IntoView {
	view! { <Text>{title}</Text> }
}

fn screen() -> Element {
	Card("Hi".to_owned()).into_view()
}

fn tuple() -> Wrapper {
	Wrapper(1)
}
"#;
	assert_eq!(rules(&lint(None, source)), [(Rule::MarkupStyle, 8)]);
}

#[test]
fn variants_and_associated_functions_are_not_components() {
	let source = r#"
fn messages() -> Vec<Message> {
	vec![Message::Text(Sender::Me, "Hi"), Self::View(1)]
}

fn qualified() -> Element {
	leptoskit::prelude::View()
}
"#;
	assert_eq!(rules(&lint(None, source)), [(Rule::MarkupStyle, 7)]);
}

#[test]
fn generated_files_are_skipped() {
	let source = format!("// @generated by `leptoskit routes`.\n{BUILDER_TREE}");
	let report = lint(None, &source);
	assert_eq!(report.files, 0);
	assert_eq!(rules(&report), []);
}

#[test]
fn builder_roots_are_found_through_fallible_calls() {
	let source = "fn tile() -> Result<Element, Error> \
	              {\n\tOk(Tile()?.child(Spacer()))\n}\n\n#[component]\nfn Tile() -> impl IntoView \
	              {}\n";
	assert_eq!(rules(&lint(None, source)), [(Rule::MarkupStyle, 2)]);
}

#[test]
fn capitalized_view_functions_need_the_component_attribute() {
	let source = r#"
fn Greeting(name: String) -> impl IntoView {
	view! { <Text>{name}</Text> }
}

#[component]
fn Farewell() -> impl IntoView {
	view! { <Text>"Bye"</Text> }
}

#[leptos::island]
fn Counter() -> impl leptos::IntoView {}

fn Builder() -> Element {
	view! { <View/> }
}

fn Config() -> Settings {
	Settings::default()
}

fn lowercase() -> impl IntoView {}
"#;
	assert_eq!(
		rules(&lint(None, source)),
		[
			(Rule::ComponentAttribute, 2),
			(Rule::ComponentAttribute, 14)
		]
	);
}

#[test]
fn levels_come_from_the_rules_table() {
	let config = "[lint.rules]\nmarkup_style = \"deny\"\ncomponent_attribute = \"allow\"\n";
	let source = format!("{BUILDER_TREE}\nfn Greeting() -> impl IntoView {{}}\n");
	let report = lint(Some(config), &source);
	assert_eq!(rules(&report), [(Rule::MarkupStyle, 3)]);
	assert_eq!(report.diagnostics[0].level, LintLevel::Deny);
	assert_eq!(report.errors(), 1);
	assert!(report.failed(false));
}

#[test]
fn a_comment_allows_the_finding_on_the_next_line() {
	let source = r#"
fn screen() -> Element {
	// leptoskit-lint: allow(markup_style)
	View().child(Text("kept"))
}

fn other() -> Element {
	// leptoskit-lint: allow(component_attribute)
	View()
}
"#;
	assert_eq!(rules(&lint(None, source)), [(Rule::MarkupStyle, 9)]);
}

#[test]
fn excluded_paths_are_skipped() {
	let report = lint(Some("[lint]\nexclude = [\"src/**\"]\n"), BUILDER_TREE);
	assert_eq!(report.files, 0);
	assert_eq!(rules(&report), []);
}

#[test]
fn unparsable_files_are_reported_and_skipped() {
	let report = lint(None, "fn broken( {");
	assert_eq!(report.files, 1);
	assert_eq!(report.unparsed.len(), 1);
	assert_eq!(rules(&report), []);
}

#[test]
fn invalid_configuration_fails_the_run() {
	let project = tempfile::tempdir().expect("scratch project");
	std::fs::write(
		project.path().join("leptoskit.toml"),
		"[lint]\nmarkup = \"html\"\n",
	)
	.expect("write config");
	std::fs::write(project.path().join("lib.rs"), "").expect("write source");
	let error = lint_paths(&[project.path().to_owned()]).expect_err("invalid markup");
	let chain: Vec<String> =
		std::iter::successors(Some(&error as &dyn std::error::Error), |error| {
			error.source()
		})
		.map(ToString::to_string)
		.collect();
	assert!(
		chain.iter().any(|message| message.contains("markup")),
		"{chain:?}"
	);
}

#[test]
fn diagnostics_render_like_rustc() {
	let report = lint(
		None,
		"fn screen() -> Element {\n\tView().child(Text(\"Hi\"))\n}\n",
	);
	let diagnostic = &report.diagnostics[0];
	let base = diagnostic
		.path
		.parent()
		.and_then(Path::parent)
		.expect("project root");
	let rendered = render_diagnostic(diagnostic, base);
	let plain = anstream::adapter::strip_str(&rendered).to_string();
	insta::assert_snapshot!(plain);
}

