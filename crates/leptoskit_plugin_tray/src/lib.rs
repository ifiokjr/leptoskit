//! Host-owned desktop tray icons. Nothing installs a process callback or
//! creates system UI until the native host explicitly calls
//! [`TrayHost::install`].
//!
//! Requires Rust 1.90. Windows and macOS hosts must pump their native event
//! loop; Linux uses a GTK-free `StatusNotifierItem` service over the session
//! D-Bus. There is no automatic guest registration or browser/mobile tray
//! emulation.

/// Maximum queued events; overflow is counted rather than allocating more.
pub const EVENT_CAPACITY: usize = 64;
/// Maximum simultaneous native icons. Linux permits one because the upstream
/// KSNI menu-change receiver is shared by competing per-tray watchers.
pub const TRAY_CAPACITY: usize = if cfg!(target_os = "linux") { 1 } else { 16 };
/// Maximum RGBA icon width or height; bounds native conversion work to 256 KiB.
pub const ICON_DIMENSION_LIMIT: u32 = 256;

/// Validation, initialization, ownership, or native failure.
#[derive(Debug, thiserror::Error)]
pub enum Error {
	/// Unsupported platform or operation.
	#[error("tray operation is unavailable on this platform")]
	Unavailable,
	/// AppKit objects must stay on the main thread.
	#[error("tray host must be created on the main thread")]
	WrongThread,
	/// The host must start its AppKit event loop first.
	#[error("the native application event loop is not running")]
	EventLoopNotRunning,
	/// Only one owner may install the upstream process-global callback.
	#[error("another tray host already owns the process callback")]
	AlreadyOwned,
	/// Invalid dimensions or an inexact RGBA byte count.
	#[error("icon must be exact RGBA pixels with dimensions in 1..=256")]
	InvalidIcon,
	/// Text is too long or contains a NUL/control character.
	#[error("tray text exceeds its limit or contains control characters")]
	InvalidText,
	/// Opaque ID does not identify a currently owned icon.
	#[error("tray icon is not owned by this host")]
	UnknownTray,
	/// Fixed capacity or unique identifier space exhausted.
	#[error("tray capacity exhausted")]
	Capacity,
	/// The operating system or native library rejected the operation.
	#[error("native tray operation failed: {0}")]
	Native(String),
}

/// Exact, validated, unpremultiplied RGBA pixels in row-major order.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RgbaIcon {
	pixels: Vec<u8>,
	width: u32,
	height: u32,
}
impl RgbaIcon {
	/// Consumes pixels after validating dimensions and exact length. No
	/// decoder, file read, scaling, or unchecked width×height
	/// multiplication is involved.
	pub fn new(pixels: Vec<u8>, width: u32, height: u32) -> Result<Self, Error> {
		if !(1..=ICON_DIMENSION_LIMIT).contains(&width)
			|| !(1..=ICON_DIMENSION_LIMIT).contains(&height)
			|| u64::from(width) * u64::from(height) * 4 != pixels.len() as u64
		{
			return Err(Error::InvalidIcon);
		}
		Ok(Self {
			pixels,
			width,
			height,
		})
	}

	/// RGBA bytes, without a copy.
	#[must_use]
	pub fn pixels(&self) -> &[u8] {
		&self.pixels
	}

	/// Width in physical pixels.
	#[must_use]
	pub fn width(&self) -> u32 {
		self.width
	}

	/// Height in physical pixels.
	#[must_use]
	pub fn height(&self) -> u32 {
		self.height
	}
}

/// Bounded text and rendering settings. Native icon identity is generated by
/// the owner; no permanent shell position/GUID settings are installed.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Options {
	/// Optional hover text, at most 127 UTF-16 code units on every platform.
	pub tooltip: Option<String>,
	/// Optional title, at most 256 UTF-8 bytes. Windows returns Unavailable.
	/// Linux exports SNI Title; the desktop decides whether/how to show it.
	pub title: Option<String>,
	/// Use alpha as an AppKit template image. Unsupported outside macOS.
	pub template: bool,
}
impl Options {
	/// Validates all options before any native resource is created or changed.
	pub fn validate(&self) -> Result<(), Error> {
		validate_tooltip(self.tooltip.as_deref())?;
		validate_title(self.title.as_deref())?;
		if self.template && !cfg!(target_os = "macos") {
			return Err(Error::Unavailable);
		}
		if self.title.is_some() && cfg!(target_os = "windows") {
			return Err(Error::Unavailable);
		}
		Ok(())
	}
}
fn validate_tooltip(text: Option<&str>) -> Result<(), Error> {
	if text.is_some_and(|value| {
		value.encode_utf16().count() > 127 || value.chars().any(char::is_control)
	}) {
		Err(Error::InvalidText)
	} else {
		Ok(())
	}
}
fn validate_title(text: Option<&str>) -> Result<(), Error> {
	if text.is_some_and(|value| value.len() > 256 || value.chars().any(char::is_control)) {
		Err(Error::InvalidText)
	} else {
		Ok(())
	}
}

/// Opaque icon identity. IDs are not reused across successive host owners.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct TrayId(u64);
/// Native mouse button, where the platform reports one.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Button {
	/// Primary mouse button.
	Left,
	/// Secondary mouse button.
	Right,
	/// Middle mouse button.
	Middle,
}
/// OS event meaning. Linux activation is deliberately distinct from a raw
/// press/release; the status-notifier protocol does not supply those
/// transitions.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EventKind {
	/// Raw button press (macOS/Windows).
	Pressed(Button),
	/// Raw button release (macOS/Windows).
	Released(Button),
	/// Double click (Windows).
	DoubleClick(Button),
	/// Linux status-notifier activation (left or middle only).
	Activated(Button),
	/// Pointer entered the icon (macOS/Windows).
	Enter,
	/// Pointer moved over the icon (macOS/Windows); adjacent moves coalesce.
	Move,
	/// Pointer left the icon (macOS/Windows).
	Leave,
}
/// Physical screen coordinates in the native desktop coordinate space.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Point {
	/// Horizontal screen coordinate.
	pub x: f64,
	/// Vertical screen coordinate.
	pub y: f64,
}
/// Native physical bounds. Linux does not expose icon bounds.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Rect {
	/// Top-left screen position in the platform coordinate system.
	pub position: Point,
	/// Physical width.
	pub width: u32,
	/// Physical height.
	pub height: u32,
}
/// One event for an icon that remains owned by this host.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Event {
	/// Originating icon.
	pub id: TrayId,
	/// Native event kind.
	pub kind: EventKind,
	/// Physical screen location when reliably supplied. Linux returns None.
	pub position: Option<Point>,
	/// Icon bounds when reliably supplied. Linux returns None.
	pub bounds: Option<Rect>,
}
/// Bounded events accumulated since the previous drain.
#[derive(Debug, Default, Clone, PartialEq)]
pub struct EventBatch {
	/// Accepted events in arrival order (adjacent moves may be replaced).
	pub events: Vec<Event>,
	/// Events discarded because the queue was full, saturating at `u64::MAX`.
	pub lost: u64,
	/// Adjacent pointer moves replaced with their latest position.
	pub coalesced: u64,
	/// A host wake callback panicked. It was caught at the native boundary.
	pub wake_failed: bool,
}

#[cfg(any(target_os = "macos", target_os = "windows", target_os = "linux"))]
mod desktop;
#[cfg(any(target_os = "macos", target_os = "windows", target_os = "linux"))]
pub use desktop::TrayHost;
#[cfg(not(any(target_os = "macos", target_os = "windows", target_os = "linux")))]
/// Unsupported browser/mobile host. No global resources are installed.
pub struct TrayHost;
#[cfg(not(any(target_os = "macos", target_os = "windows", target_os = "linux")))]
impl TrayHost {
	/// Returns Unavailable without invoking the callback or creating UI.
	pub fn install(_: impl Fn() + Send + Sync + 'static) -> Result<Self, Error> {
		Err(Error::Unavailable)
	}
}

#[cfg(test)]
mod tests {
	use super::*;
	#[test]
	fn icons_reject_overflow_empty_and_inexact_buffers() {
		for (width, height) in [(0, 1), (1, 0), (257, 1), (u32::MAX, u32::MAX)] {
			assert!(RgbaIcon::new(vec![], width, height).is_err());
		}
		assert!(RgbaIcon::new(vec![0; 3], 1, 1).is_err());
		assert!(RgbaIcon::new(vec![0; 5], 1, 1).is_err());
		let icon = RgbaIcon::new(vec![0, 1, 2, 255], 1, 1).unwrap();
		assert_eq!(icon.pixels(), &[0, 1, 2, 255]);
		assert_eq!((icon.width(), icon.height()), (1, 1));
	}
	#[test]
	fn text_limits_count_windows_utf16_without_truncating() {
		assert!(validate_tooltip(Some(&"🦀".repeat(64))).is_err());
		assert!(validate_tooltip(Some(&"🦀".repeat(63))).is_ok());
		assert!(validate_tooltip(Some("hidden\0text")).is_err());
		assert!(validate_title(Some(&"a".repeat(257))).is_err());
	}
}
