//! Wall-clock datetimes and times, durations, and sequences, against both
//! databases.

#![cfg(all(feature = "postgres", feature = "sqlite"))]

mod support;

use std::future::Future;

use chrono::Duration;
use chrono::NaiveDate;
use chrono::NaiveDateTime;
use chrono::NaiveTime;
use leptoskit_db::Db;
use leptoskit_db::Id;
use leptoskit_db::table;
use leptoskit_db_schema::Dialect;
use leptoskit_db_schema::RequireHints;
use leptoskit_db_schema::Schema;

/// Something scheduled on a calendar in no particular time zone.
#[table(name = "schedules")]
pub struct Schedule {
	pub id: Id<Self>,
	pub title: String,
	/// When it starts, as the calendar on the wall reads it.
	pub starts: NaiveDateTime,
	/// When doors open that day.
	pub doors: NaiveTime,
	/// How long the grace period runs.
	pub grace: Duration,
}

async fn create_schema(db: &Db) {
	let dialect = db.dialect();
	let schema = leptoskit_db::schema(dialect).unwrap();
	let empty = Schema::empty(dialect);
	let plan = leptoskit_db_schema::diff(&empty, &schema, &mut RequireHints).unwrap();
	let migration = leptoskit_db_schema::render(&plan, &empty, &schema);
	db.run_script(&migration.statements.join(";\n"))
		.await
		.unwrap();
}

async fn on_both<F, Fut>(check: F)
where
	F: Fn(Db) -> Fut,
	Fut: Future<Output = ()>,
{
	let db = Db::connect("sqlite::memory:").await.unwrap();
	check(db).await;

	if let Some(cluster) = support::postgres::PostgresCluster::start() {
		let db = Db::connect(&cluster.database()).await.unwrap();
		check(db).await;
	}
}

#[tokio::test(flavor = "multi_thread")]
async fn wall_clock_times_and_durations_round_trip() {
	on_both(async |db| {
		create_schema(&db).await;
		let starts = NaiveDate::from_ymd_opt(2026, 11, 6)
			.unwrap()
			.and_hms_micro_opt(9, 30, 0, 500_000)
			.unwrap();
		let schedule = NewSchedule {
			title: "Keynote".into(),
			starts,
			doors: NaiveTime::from_hms_opt(8, 45, 0).unwrap(),
			grace: Duration::minutes(90) + Duration::milliseconds(500),
		}
		.insert(&db)
		.await
		.unwrap();

		assert_eq!(schedule.starts, starts);
		assert_eq!(schedule.doors, NaiveTime::from_hms_opt(8, 45, 0).unwrap());
		assert_eq!(
			schedule.grace,
			Duration::minutes(90) + Duration::milliseconds(500)
		);

		// Durations can be negative, and ISO 8601 text is what both
		// databases hold.
		let read = Schedule::get(&db, schedule.id).await.unwrap();
		assert_eq!(read.grace, schedule.grace);

		NewSchedule {
			title: "Cleanup".into(),
			starts,
			doors: NaiveTime::from_hms_opt(8, 45, 0).unwrap(),
			grace: -Duration::hours(36),
		}
		.insert(&db)
		.await
		.unwrap();
		let negative = Schedule::query()
			.filter(|schedule| schedule.title.eq("Cleanup"))
			.one(&db)
			.await
			.unwrap();
		assert_eq!(negative.grace, -Duration::hours(36));

		// The values filter and order by like any column.
		let morning = Schedule::query()
			.filter(|schedule| schedule.doors.lt(NaiveTime::from_hms_opt(9, 0, 0).unwrap()))
			.count(&db)
			.await
			.unwrap();
		assert_eq!(morning, 2);
	})
	.await;
}

#[tokio::test(flavor = "multi_thread")]
async fn sequences_number_rows_in_order() {
	use leptoskit_db::Read as _;
	use leptoskit_db::Statement;
	use leptoskit_db::Value;
	use leptoskit_db_schema::Column as ModelColumn;
	use leptoskit_db_schema::ColumnType;
	use leptoskit_db_schema::Table as ModelTable;
	use leptoskit_db_schema::TableName;

	// The model refuses the column for SQLite, with a way out.
	let invoices = ModelTable::new(
		TableName::new("invoices"),
		vec![
			ModelColumn::new("id", ColumnType::Uuid),
			ModelColumn::new("number", ColumnType::Sequence),
		],
		vec!["id".into()],
	);
	let sqlite = Schema::new(Dialect::Sqlite, vec![invoices.clone()]);
	assert!(
		sqlite
			.problems()
			.iter()
			.any(|problem| problem.to_string().contains("in order")),
		"{:?}",
		sqlite.problems()
	);

	let Some(cluster) = support::postgres::PostgresCluster::start() else {
		return;
	};
	let db = Db::connect(&cluster.database()).await.unwrap();
	let postgres = Schema::new(Dialect::Postgres, vec![invoices]);
	let empty = Schema::empty(Dialect::Postgres);
	let plan = leptoskit_db_schema::diff(&empty, &postgres, &mut RequireHints).unwrap();
	let migration = leptoskit_db_schema::render(&plan, &empty, &postgres);
	assert!(
		migration.sql().contains("generated by default as identity"),
		"{}",
		migration.sql()
	);
	db.run_script(&migration.statements.join(";\n"))
		.await
		.unwrap();

	// The database numbers the rows, in order, without the insert naming
	// the column.
	let insert = db
		.fetch(Statement {
			sql: "INSERT INTO invoices (id) VALUES ($1) RETURNING number".into(),
			args: vec![Value::Uuid(uuid::Uuid::now_v7())],
		})
		.await
		.unwrap();
	let second_insert = db
		.fetch(Statement {
			sql: "INSERT INTO invoices (id) VALUES ($1) RETURNING number".into(),
			args: vec![Value::Uuid(uuid::Uuid::now_v7())],
		})
		.await
		.unwrap();
	let (first, second) = match (insert[0][0].clone(), second_insert[0][0].clone()) {
		(Value::Int(first), Value::Int(second)) => (first, second),
		other => panic!("numbers came back as {other:?}"),
	};
	assert_eq!((first, second), (1, 2), "numbered from 1, in order");
}
