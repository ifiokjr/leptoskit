//! The HTML and JavaScript an extension package needs around the app's wasm.
//!
//! Extension pages forbid inline scripts, so every page is a static file
//! that loads its own module. Nothing here is app code: each file starts the
//! app's wasm at a surface, or, for content scripts, connects the page to
//! the frame the app runs in.

use std::fmt::Write as _;

use leptoskit_config::extension::BACKGROUND_EVENTS;

/// The wasm-bindgen module's file stem, such as `commonplace_app`.
pub struct Module<'a> {
	pub stem: &'a str,
}

fn js_string(value: &str) -> String {
	serde_json::to_string(value).expect("strings serialize")
}

fn escape_html(value: &str) -> String {
	value
		.replace('&', "&amp;")
		.replace('<', "&lt;")
		.replace('>', "&gt;")
		.replace('"', "&quot;")
}

/// A page surface's HTML. The popup gets a size, because browsers size it
/// to its content.
#[must_use]
pub fn page_html(surface: &str, title: &str, stylesheet: bool) -> String {
	let sizing = match surface {
		"popup" => {
			"\n    <style>html, body { margin: 0; width: 380px; min-height: 480px; }</style>"
		}
		"overlay" => "\n    <style>html, body { margin: 0; background: transparent; }</style>",
		_ => "\n    <style>html, body { margin: 0; }</style>",
	};
	let stylesheet = if stylesheet {
		"\n    <link rel=\"stylesheet\" href=\"assets/app.css\" />"
	} else {
		""
	};
	format!(
		"<!doctype html>\n<html lang=\"en\">\n  <head>\n    <meta charset=\"utf-8\" />\n    <meta \
		 name=\"viewport\" content=\"width=device-width, initial-scale=1\" />\n    \
		 <title>{title}</title>{stylesheet}{sizing}\n    <script type=\"module\" \
		 src=\"{surface}.js\"></script>\n  </head>\n  <body></body>\n</html>\n",
		title = escape_html(title),
	)
}

/// A page surface's module: starts the app's wasm at the configured route.
#[must_use]
pub fn page_js(module: &Module<'_>, surface: &str, route: &str) -> String {
	format!(
		"// Generated by leptoskit: the {surface} surface, at {route}.\nimport init, {{ \
		 leptoskit_extension_start }} from \"./pkg/{stem}.js\";\n\nawait init({{ module_or_path: \
		 new URL(\"./pkg/{stem}_bg.wasm\", import.meta.url) }});\nleptoskit_extension_start({}, \
		 {});\n",
		js_string(surface),
		js_string(route),
		stem = module.stem,
	)
}

/// The overlay frame's module: starts the app at the content script's
/// surface and route, which the content script passes in the address's
/// fragment.
#[must_use]
pub fn overlay_js(module: &Module<'_>) -> String {
	format!(
		"// Generated by leptoskit: a content script's interface, in the extension's own \
		 frame.\nimport init, {{ leptoskit_extension_start }} from \"./pkg/{stem}.js\";\n\nconst \
		 frame = JSON.parse(decodeURIComponent(location.hash.slice(1)));\nawait init({{ \
		 module_or_path: new URL(\"./pkg/{stem}_bg.wasm\", import.meta.url) \
		 }});\nleptoskit_extension_start(\"content:\" + frame.name, frame.route);\n",
		stem = module.stem,
	)
}

/// How each background event is listened to: the browser's event, and the
/// expression that turns its arguments into the event's details.
fn listener(event: &str) -> (&'static str, &'static str, &'static str) {
	match event {
		"runtime.installed" => ("runtime.onInstalled", "(details)", "details"),
		"runtime.startup" => ("runtime.onStartup", "()", "null"),
		"runtime.connect" => ("runtime.onConnect", "(port)", "({ name: port.name })"),
		"alarms" => ("alarms.onAlarm", "(alarm)", "alarm"),
		"context_menus" => ("contextMenus.onClicked", "(info, tab)", "({ info, tab })"),
		"commands" => ("commands.onCommand", "(command, tab)", "({ command, tab })"),
		"tabs.updated" => {
			(
				"tabs.onUpdated",
				"(tabId, changeInfo, tab)",
				"({ tabId, changeInfo, tab })",
			)
		}
		"storage.changed" => {
			(
				"storage.onChanged",
				"(changes, area)",
				"({ changes, area })",
			)
		}
		other => unreachable!("validation accepts only known events, not {other}"),
	}
}

/// The background worker. Browsers start it cold for each event, and only
/// deliver events to listeners registered on its first turn, so it
/// registers every listener at once and queues events until the wasm is
/// ready. Then it runs the app's `background` function and hands over the
/// queue. `events` is `None` when the app has no background function, which
/// a development build still needs a worker for. `dev`, the dev server,
/// makes it reload the extension after each rebuild.
#[must_use]
pub fn background_js(module: &Module<'_>, events: Option<&[String]>, dev: Option<&str>) -> String {
	let mut listeners = String::new();
	let configured = events.unwrap_or_default();
	for event in BACKGROUND_EVENTS {
		if !configured.iter().any(|configured| configured == event) {
			continue;
		}
		if event == "runtime.message" {
			listeners.push_str(
				"api.runtime.onMessage.addListener((message, sender, sendResponse) => {\n  \
				 deliver(\"runtime.message\", { message, sender }, sendResponse);\n  // Keeps the \
				 channel open for the reply, in every browser.\n  return true;\n});\n",
			);
			continue;
		}
		let (path, parameters, detail) = listener(event);
		if event == "runtime.connect" {
			let _ = write!(
				listeners,
				"api.{path}.addListener({parameters} => {{\n  // A content script's private \
				 channel belongs to its frame.\n  if (port.name.startsWith(\"leptoskit-page:\")) \
				 return;\n  deliver({}, {detail});\n}});\n",
				js_string(event)
			);
			continue;
		}
		let _ = writeln!(
			listeners,
			"api.{path}.addListener({parameters} => deliver({}, {detail}));",
			js_string(event)
		);
	}
	let reload = dev.map_or_else(String::new, |server| {
		format!(
			"// Development: reload the extension when `leptoskit dev` finishes a new \
			 build.\n(async () => {{\n  let after = \"\";\n  for (;;) {{\n    try {{\n      const \
			 response = await fetch({} + \"/_leptoskit/extension/build?after=\" + after);\n      \
			 const build = await response.text();\n      if (after && build !== after) return \
			 api.runtime.reload();\n      after = build;\n    }} catch {{\n      await new \
			 Promise((resolve) => setTimeout(resolve, 1000));\n    }}\n  }}\n}})();\n",
			js_string(server)
		)
	});
	let Some(_) = events else {
		return format!(
			"// Generated by leptoskit: the development worker.\nconst api = globalThis.browser \
			 ?? globalThis.chrome;\n\n{reload}"
		);
	};
	let reload = if reload.is_empty() {
		reload
	} else {
		format!("\n{reload}")
	};
	format!(
		"// Generated by leptoskit: the background worker.\nimport init, {{ \
		 leptoskit_extension_background, leptoskit_extension_event }} from \
		 \"./pkg/{stem}.js\";\n\nconst api = globalThis.browser ?? globalThis.chrome;\nlet ready \
		 = false;\nconst queue = [];\n\n// Every event reaches the app's handler once the wasm is \
		 ready; a reply goes back to the\n// sender, and a failure as `{{ __leptoskit_error \
		 }}`.\nfunction deliver(kind, detail, reply) {{\n  const run = () =>\n    \
		 leptoskit_extension_event(kind, detail ?? null).then(\n      (answer) => \
		 reply?.(answer),\n      (error) => reply?.({{ __leptoskit_error: String(error?.message \
		 ?? error) }}),\n    );\n  if (ready) run();\n  else \
		 queue.push(run);\n}}\n\n{listeners}\ninit({{ module_or_path: new \
		 URL(\"./pkg/{stem}_bg.wasm\", import.meta.url) }}).then(() => {{\n  \
		 leptoskit_extension_background();\n  ready = true;\n  for (const run of queue.splice(0)) \
		 run();\n}});\n{reload}",
		stem = module.stem,
	)
}

/// A content script. It runs no wasm: most large sites' content security
/// policies stop wasm from compiling in the page. It puts a frame of the
/// extension's own `overlay.html` on the page, in a closed shadow root, and
/// answers the frame's requests over a private port: the page's details,
/// the selection, placing the frame, and highlighting quotes.
#[must_use]
pub fn content_js(name: &str, route: &str) -> String {
	CONTENT_TEMPLATE
		.replace("__NAME__", &js_string(name))
		.replace("__ROUTE__", &js_string(route))
		.replace("__LABEL__", name)
}

const CONTENT_TEMPLATE: &str = r##"// Generated by leptoskit: the content script "__LABEL__".
(() => {
  const api = globalThis.browser ?? globalThis.chrome;
  const name = __NAME__;
  const key = "__leptoskit_content_" + name;
  // Injected again into the same page: keep the frame that is there.
  if (globalThis[key]) return;
  globalThis[key] = true;

  const nonce = crypto.randomUUID();
  const host = document.createElement("leptoskit-frame");
  Object.assign(host.style, {
    all: "initial",
    position: "fixed",
    zIndex: "2147483647",
    top: "0",
    left: "0",
    width: "0",
    height: "0",
    display: "block",
  });
  const shadow = host.attachShadow({ mode: "closed" });
  const frame = document.createElement("iframe");
  Object.assign(frame.style, {
    border: "0",
    width: "100%",
    height: "100%",
    colorScheme: "normal",
    background: "transparent",
    borderRadius: "12px",
    boxShadow: "0 8px 30px rgba(0, 0, 0, 0.25)",
  });
  frame.src =
    api.runtime.getURL("overlay.html") +
    "#" +
    encodeURIComponent(JSON.stringify({ nonce, name, route: __ROUTE__ }));
  shadow.append(frame);
  (document.body ?? document.documentElement).append(host);

  const squash = (text) => text.replace(/\s+/g, " ");
  const meta = (selector) => document.querySelector(selector)?.getAttribute("content")?.trim() || null;
  const date = (text) => {
    const day = (text ?? "").slice(0, 10);
    return /^\d{4}(-\d{2}(-\d{2})?)?$/.test(day) ? day : null;
  };

  function info() {
    return {
      url: location.href.split("#")[0],
      title: meta('meta[property="og:title"]') ?? document.title,
      author: meta('meta[name="author"]') ?? meta('meta[property="article:author"]'),
      site: meta('meta[property="og:site_name"]'),
      published: date(
        meta('meta[property="article:published_time"]') ??
          document.querySelector("time[datetime]")?.getAttribute("datetime"),
      ),
      description: meta('meta[name="description"]') ?? meta('meta[property="og:description"]'),
    };
  }

  // Up to 32 characters of the page's text on each side of a range.
  function around(range) {
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    const start = range.startContainer;
    let before = start.nodeType === Node.TEXT_NODE ? start.data.slice(0, range.startOffset) : "";
    walker.currentNode = start;
    while (before.length < 64 && walker.previousNode()) before = walker.currentNode.data + before;
    const end = range.endContainer;
    let after = end.nodeType === Node.TEXT_NODE ? end.data.slice(range.endOffset) : "";
    walker.currentNode = end;
    while (after.length < 64 && walker.nextNode()) after += walker.currentNode.data;
    return { before: squash(before).slice(-32), after: squash(after).slice(0, 32) };
  }

  function selection() {
    const current = getSelection();
    if (!current || current.isCollapsed || current.rangeCount === 0) return null;
    const range = current.getRangeAt(0);
    const text = squash(current.toString()).trim();
    if (!text) return null;
    const rect = range.getBoundingClientRect();
    return {
      text,
      ...around(range),
      rect: { x: rect.x, y: rect.y, width: rect.width, height: rect.height },
    };
  }

  function place(placement) {
    const size = (width, height, top, left) =>
      Object.assign(host.style, {
        width: width + "px",
        height: height + "px",
        top: top + "px",
        left: left + "px",
      });
    if (placement.at === "hidden") return size(0, 0, 0, 0);
    const width = Math.min(placement.width, innerWidth - 16);
    const height = Math.min(placement.height, innerHeight - 16);
    if (placement.at === "corner") return size(width, height, 16, innerWidth - width - 16);
    const rect = getSelection()?.rangeCount ? getSelection().getRangeAt(0).getBoundingClientRect() : null;
    const top = rect ? Math.min(rect.bottom + 8, innerHeight - height - 8) : 16;
    const left = rect ? Math.max(8, Math.min(rect.left, innerWidth - width - 8)) : innerWidth - width - 16;
    size(width, height, Math.max(8, top), left);
  }

  // The page's text with runs of whitespace collapsed, and where each
  // character came from, so a quote can be found however the page wraps it.
  function index() {
    const text = [];
    const at = [];
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode: (node) =>
        node.parentElement?.closest("script, style, noscript, leptoskit-frame")
          ? NodeFilter.FILTER_REJECT
          : NodeFilter.FILTER_ACCEPT,
    });
    let space = true;
    while (walker.nextNode()) {
      const node = walker.currentNode;
      for (let offset = 0; offset < node.data.length; offset++) {
        const character = node.data[offset];
        if (/\s/.test(character)) {
          if (space) continue;
          space = true;
          text.push(" ");
        } else {
          space = false;
          text.push(character);
        }
        at.push([node, offset]);
      }
    }
    return { text: text.join(""), at };
  }

  // Where a quote is, preferring the occurrence its context matches.
  function locate(page, quote) {
    const exact = squash(quote.exact).trim();
    if (!exact) return null;
    const prefix = quote.prefix ? squash(quote.prefix) : null;
    const suffix = quote.suffix ? squash(quote.suffix) : null;
    let best = null;
    for (let start = page.text.indexOf(exact); start !== -1; start = page.text.indexOf(exact, start + 1)) {
      const end = start + exact.length;
      let score = 0;
      if (prefix && page.text.slice(0, start).trimEnd().endsWith(prefix.trimEnd())) score++;
      if (suffix && page.text.slice(end).trimStart().startsWith(suffix.trimStart())) score++;
      if (!best || score > best.score) best = { start, end, score };
    }
    return best;
  }

  function wrap(page, found, id) {
    const pieces = new Map();
    for (let position = found.start; position < found.end; position++) {
      const [node, offset] = page.at[position];
      const piece = pieces.get(node) ?? { from: offset, to: offset };
      piece.to = offset + 1;
      pieces.set(node, piece);
    }
    for (const [node, piece] of pieces) {
      const range = document.createRange();
      range.setStart(node, piece.from);
      range.setEnd(node, piece.to);
      const mark = document.createElement("mark");
      mark.dataset.leptoskitQuote = id;
      Object.assign(mark.style, { background: "#fde68a", color: "inherit", cursor: "pointer", borderRadius: "2px" });
      mark.addEventListener("click", () => emit("highlight_pressed", id));
      range.surroundContents(mark);
    }
  }

  function clear() {
    for (const mark of document.querySelectorAll("mark[data-leptoskit-quote]")) {
      const parent = mark.parentNode;
      mark.replaceWith(...mark.childNodes);
      parent?.normalize();
    }
  }

  function highlight(quotes) {
    clear();
    let found = 0;
    for (const quote of quotes ?? []) {
      // Each wrap changes the text nodes, so index the page again.
      const page = index();
      const at = locate(page, quote);
      if (!at) continue;
      wrap(page, at, quote.id);
      found++;
    }
    return found;
  }

  function scrollTo(id) {
    const mark = document.querySelector(`mark[data-leptoskit-quote="${CSS.escape(id)}"]`);
    mark?.scrollIntoView({ block: "center", behavior: "smooth" });
    return Boolean(mark);
  }

  let port = null;
  const emit = (event, data) => port?.postMessage({ event, data });
  const methods = {
    info,
    selection,
    place,
    highlight,
    scroll_to: scrollTo,
    close() {
      clear();
      host.remove();
      globalThis[key] = false;
      setTimeout(() => port?.disconnect(), 0);
      return null;
    },
  };

  // Only this script's frame knows the nonce, so only it can connect.
  api.runtime.onConnect.addListener((connected) => {
    if (connected.name !== "leptoskit-page:" + nonce) return;
    port = connected;
    port.onDisconnect.addListener(() => (port = null));
    port.onMessage.addListener(async (message) => {
      try {
        const method = methods[message.method];
        if (!method) throw new Error("no page method " + message.method);
        port?.postMessage({ id: message.id, result: (await method(message.params)) ?? null });
      } catch (error) {
        port?.postMessage({ id: message.id, error: String(error?.message ?? error) });
      }
    });
  });

  let pending = 0;
  document.addEventListener("selectionchange", () => {
    clearTimeout(pending);
    pending = setTimeout(() => emit("selection", selection()), 250);
  });
})();
"##;

#[cfg(test)]
mod tests {
	use super::*;

	#[test]
	fn pages_load_their_module_and_nothing_inline() {
		let html = page_html("popup", "Commonplace <beta>", true);
		assert!(html.contains("<script type=\"module\" src=\"popup.js\"></script>"));
		assert!(html.contains("Commonplace &lt;beta&gt;"));
		assert!(
			!html.contains("<script>") && !html.contains("<script type=\"module\">"),
			"extension pages forbid inline scripts"
		);
	}

	#[test]
	fn generated_scripts() {
		let module = Module { stem: "app" };
		insta::assert_snapshot!("popup_js", page_js(&module, "popup", "/clip"));
		insta::assert_snapshot!("overlay_js", overlay_js(&module));
		insta::assert_snapshot!(
			"background_js",
			background_js(
				&module,
				Some(&[
					"runtime.message".into(),
					"context_menus".into(),
					"alarms".into()
				]),
				None
			)
		);
		insta::assert_snapshot!(
			"background_dev_js",
			background_js(&module, None, Some("http://127.0.0.1:3000"))
		);
		let content = content_js("clipper", "/overlay/clipper");
		assert!(content.contains("const name = \"clipper\";"));
		assert!(content.contains("route: \"/overlay/clipper\""));
		for placeholder in ["__NAME__", "__ROUTE__", "__LABEL__"] {
			assert!(!content.contains(placeholder), "{placeholder} is filled");
		}
	}
}
