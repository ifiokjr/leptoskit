use std::fmt::Write as _;

use super::*;

pub(super) fn generate(root: &Path, registry: &Registry, abi: &str) -> Result<()> {
	let dir = root.join(".leptoskit/android");
	write(
		&dir.join("plugin-dependencies.txt"),
		&android_dependencies(registry),
	)?;
	write(&dir.join("abi.txt"), abi)?;
	let sources = dir.join("sources");
	ensure_directory(&sources)?;
	copy_sources(registry, &sources)?;
	let kotlin = android_registrant(registry, &sources)?;
	write(&sources.join("GeneratedPlugins.kt"), &kotlin)?;

	write_manifest(root, registry, &dir)?;
	write_cmake(root, registry, &dir)
}

fn copy_sources(registry: &Registry, sources: &Path) -> Result<()> {
	// Replaced as one generated source tree; removed dependencies cannot leave
	// an old registrant or handler compiled into the next application.
	for entry in std::fs::read_dir(sources)? {
		let path = entry?.path();
		anyhow::ensure!(
			path.is_file() && !path.is_symlink(),
			"unexpected generated source entry {}",
			path.display()
		);

		std::fs::remove_file(path)?;
	}

	std::fs::copy(
		registry.bridge.join("android/NativePlugin.kt"),
		sources.join("NativePlugin.kt"),
	)?;
	std::fs::copy(
		registry.bridge.join("mobile/LeptosKitView.kt"),
		sources.join("LeptosKitView.kt"),
	)?;

	for source in [
		"android/NativePermissionHost.kt",
		"android/NativeActivityResultHost.kt",
		"mobile/NativeApp.kt",
		"mobile/NativeRustWorker.kt",
		"mobile/NativeReleases.kt",
		"mobile/LeptosKitApplicationView.kt",
		"mobile/NativeRustAsync.kt",
	] {
		copy(
			&registry.bridge.join(source),
			&sources.join(
				Path::new(source)
					.file_name()
					.context("native source filename missing")?,
			),
		)?;
	}

	Ok(())
}

/// Keep Rust implementations out of the platform dispatcher to avoid duplicate
/// registration.
fn android_registrant(registry: &Registry, sources: &Path) -> Result<String> {
	let mut kotlin = String::from(
		"// Generated by leptoskit.\npackage dev.leptoskit.mobile\nimport \
		 android.content.Context\nimport dev.leptoskit.bridge.NativeDispatcher\nobject \
		 GeneratedPlugins {\n    fun register(context: Context, bridge: Long, dispatcher: \
		 NativeDispatcher) {\n",
	);

	for (index, plugin) in registry.plugins.iter().enumerate() {
		if plugin.rust_type.is_some() || plugin.rust_factory.is_some() {
			continue;
		}

		writeln!(
			kotlin,
			"        dispatcher.register(bridge, {}({}))",
			plugin
				.android_type
				.as_deref()
				.context("missing Android plugin")?,
			if plugin.android_context {
				"context"
			} else {
				""
			}
		)?;
		copy_kotlin(&plugin.directory, sources, &format!("plugin_{index}"))?;
	}

	for (index, helper) in registry.support.iter().enumerate() {
		if helper.android {
			copy_kotlin(&helper.directory, sources, &format!("support_{index}"))?;
		}
	}

	kotlin.push_str("    }\n}\n");
	Ok(kotlin)
}

fn write_manifest(root: &Path, registry: &Registry, dir: &Path) -> Result<()> {
	let manifest = std::fs::read_to_string(
		super::super::host_dir(root, Target::Android).join("app/src/main/AndroidManifest.xml"),
	)?;
	let mut permissions = std::collections::BTreeSet::new();
	let mut query_actions = std::collections::BTreeSet::new();

	for plugin in &registry.plugins {
		permissions.extend(plugin.android_permissions.iter().map(String::as_str));
		query_actions.extend(plugin.android_query_actions.iter().map(String::as_str));
	}

	let manifest = super::super::manifest::merge(&manifest, &permissions, &query_actions)?;
	write(&dir.join("AndroidManifest.xml"), &manifest)
}

fn write_cmake(root: &Path, registry: &Registry, dir: &Path) -> Result<()> {
	let cmake = format!(
		"cmake_minimum_required(VERSION 3.22)\nproject(leptoskit_app LANGUAGES \
		 CXX)\nadd_library(runtime STATIC IMPORTED)\nset_target_properties(runtime PROPERTIES \
		 IMPORTED_LOCATION {})\nadd_library(leptoskit_bridge_jni SHARED {} \
		 {})\ntarget_compile_features(leptoskit_bridge_jni PRIVATE \
		 cxx_std_20)\ntarget_compile_options(leptoskit_bridge_jni PRIVATE -Wall -Wextra \
		 -Werror)\n# Section-per-function plus garbage collection at link: lld already drops \
		 unused archive members, and these flags also prune unused sections within the members it \
		 pulls.\ntarget_compile_options(leptoskit_bridge_jni PRIVATE -ffunction-sections \
		 -fdata-sections)\ntarget_link_options(leptoskit_bridge_jni PRIVATE \
		 -Wl,--gc-sections)\ntarget_link_libraries(leptoskit_bridge_jni PRIVATE runtime log \
		 android dl m)\n",
		quote(
			&super::super::generated_dir(root, Target::Android)
				.join("lib/libleptoskit_bridge_ffi.a")
		)?,
		quote(&registry.bridge.join("android/bridge.cpp"))?,
		quote(&registry.bridge.join("mobile/app.cpp"))?
	);
	write(&dir.join("CMakeLists.txt"), &cmake)
}
fn android_dependencies(registry: &Registry) -> String {
	let dependencies: std::collections::BTreeSet<_> = registry
		.plugins
		.iter()
		.flat_map(|plugin| &plugin.android_dependencies)
		.collect();
	let mut output = String::new();

	for dependency in dependencies {
		output.push_str(dependency);
		output.push('\n');
	}

	output
}

fn copy_kotlin(package: &Path, destination: &Path, prefix: &str) -> Result<()> {
	let sources = package.join("android");
	anyhow::ensure!(
		!sources.is_symlink() && sources.is_dir(),
		"Android source directory must be ordinary: {}",
		sources.display()
	);

	for entry in std::fs::read_dir(sources)? {
		let path = entry?.path();

		if path.extension().is_some_and(|extension| extension == "kt") {
			anyhow::ensure!(
				path.is_file() && !path.is_symlink(),
				"Android source must be a regular file: {}",
				path.display()
			);
			let filename = path
				.file_name()
				.context("native source filename missing")?
				.to_str()
				.context("native source filename must be UTF-8")?;
			copy(&path, &destination.join(format!("{prefix}_{filename}")))?;
		}
	}

	Ok(())
}
