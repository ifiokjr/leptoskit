//! The Safari extension inside the macOS and iOS apps.
//!
//! Safari runs a web extension only from an app extension with the
//! `com.apple.Safari.web-extension` extension point, inside an app. When
//! `[extension].browsers` has `safari`, the native build packages the
//! extension for Safari and puts it in the app: on macOS by assembling
//! `Contents/PlugIns/SafariExtension.appex` next to the app it assembles,
//! and on iOS as a second target in the generated Xcode project.

use std::path::Path;
use std::path::PathBuf;
use std::process::Command;

use anyhow::Context;
use anyhow::Result;
use leptoskit_config::Browser;
use leptoskit_config::LeptoskitConfig;

use super::project::copy;
use super::project::write;

/// The app extension's name, which is also its executable's.
pub const NAME: &str = "SafariExtension";

/// Whether the app carries a Safari extension.
#[must_use]
pub fn configured(config: &LeptoskitConfig) -> bool {
	config
		.app
		.platforms
		.contains(&leptoskit_config::Platform::Extension)
		&& config
			.extension
			.as_ref()
			.is_some_and(|extension| extension.browsers.contains(&Browser::Safari))
}

/// The Safari extension's bundle identifier, which Apple requires to start
/// with the app's.
#[must_use]
pub fn bundle_id(config: &LeptoskitConfig) -> String {
	let suffix = config
		.extension
		.as_ref()
		.map_or("SafariExtension", |extension| {
			extension.safari.bundle_id_suffix.as_str()
		});
	format!("{}.{suffix}", config.native.package_id)
}

/// Builds Safari's package of the extension, when the app has one, and
/// returns its folder.
///
/// # Errors
///
/// When the extension build fails.
pub fn prepare(config: &LeptoskitConfig, release: bool) -> Result<Option<PathBuf>> {
	if !configured(config) {
		return Ok(None);
	}
	let built = crate::extension::build_for(release, None, &[Browser::Safari])?;
	Ok(built.packages.into_iter().next().map(|package| package.dir))
}

/// The app extension's principal class: it answers the extension's native
/// messages, which leptoskit doesn't use yet.
#[must_use]
pub fn handler_swift() -> &'static str {
	r#"// Generated by leptoskit: the Safari extension's principal class.
import Foundation
import SafariServices

@objc(SafariWebExtensionHandler)
final class SafariWebExtensionHandler: NSObject, NSExtensionRequestHandling {
    func beginRequest(with context: NSExtensionContext) {
        let response = NSExtensionItem()
        response.userInfo = [SFExtensionMessageKey: ["native": false]]
        context.completeRequest(returningItems: [response], completionHandler: nil)
    }
}
"#
}

/// The app extension's `Info.plist`.
#[must_use]
pub fn info_plist(config: &LeptoskitConfig, macos: bool, build_number: u64) -> String {
	let name = config
		.extension
		.as_ref()
		.and_then(|extension| extension.name.clone())
		.unwrap_or_else(|| config.app.name.clone());
	let version = &config.app.version;
	let minimum = if macos {
		"<key>LSMinimumSystemVersion</key><string>14.0</string>"
	} else {
		"<key>MinimumOSVersion</key><string>17.0</string>"
	};
	// The App Store requires an extension's versions to match its app's: on
	// iOS both come from the Xcode project's build settings, which
	// `leptoskit publish` sets; the macOS app is assembled with them.
	let (short, build) = if macos {
		(
			format!("{}.{}.{}", version.major, version.minor, version.patch),
			build_number.to_string(),
		)
	} else {
		(
			"$(MARKETING_VERSION)".to_owned(),
			"$(CURRENT_PROJECT_VERSION)".to_owned(),
		)
	};
	format!(
		r#"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleDevelopmentRegion</key><string>en</string>
	<key>CFBundleDisplayName</key><string>{name}</string>
	<key>CFBundleExecutable</key><string>{NAME}</string>
	<key>CFBundleIdentifier</key><string>{bundle}</string>
	<key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
	<key>CFBundleName</key><string>{NAME}</string>
	<key>CFBundlePackageType</key><string>XPC!</string>
	<key>CFBundleShortVersionString</key><string>{short}</string>
	<key>CFBundleVersion</key><string>{build}</string>
	{minimum}
	<key>NSExtension</key>
	<dict>
		<key>NSExtensionPointIdentifier</key><string>com.apple.Safari.web-extension</string>
		<key>NSExtensionPrincipalClass</key><string>SafariWebExtensionHandler</string>
	</dict>
	<key>NSHumanReadableDescription</key><string>{description}</string>
</dict>
</plist>
"#,
		name = escape(&name),
		bundle = escape(&bundle_id(config)),
		description = escape(
			config
				.extension
				.as_ref()
				.and_then(|extension| extension.description.as_deref())
				.unwrap_or_default()
		),
	)
}

fn escape(value: &str) -> String {
	value
		.replace('&', "&amp;")
		.replace('<', "&lt;")
		.replace('>', "&gt;")
}

/// The entitlements Safari requires of an app extension: the App Sandbox,
/// and nothing more.
pub const ENTITLEMENTS: &str = r#"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>com.apple.security.app-sandbox</key><true/>
</dict>
</plist>
"#;

/// Assembles the Safari extension into the macOS app at `application`, and
/// signs it, before the app itself is signed.
///
/// # Errors
///
/// When compiling the handler, copying the package, or signing fails.
pub fn assemble_macos(
	root: &Path,
	config: &LeptoskitConfig,
	application: &Path,
	package: &Path,
) -> Result<()> {
	let work = root.join(".leptoskit/macos").join(NAME);
	write(
		&work.join("SafariWebExtensionHandler.swift"),
		handler_swift(),
	)?;
	write(&work.join("entitlements.plist"), ENTITLEMENTS)?;
	let binary = work.join(NAME);
	super::run_tool(
		Command::new("swiftc")
			.args(["-parse-as-library", "-application-extension", "-O"])
			.args(["-module-name", NAME, "-target", "arm64-apple-macos14"])
			.arg(work.join("SafariWebExtensionHandler.swift"))
			.args(["-framework", "SafariServices"])
			// An app extension's entry point is the system's, not `main`.
			.args(["-Xlinker", "-e", "-Xlinker", "_NSExtensionMain"])
			.arg("-o")
			.arg(&binary),
	)
	.context("compiling the Safari extension's handler")?;

	let appex = application
		.join("Contents/PlugIns")
		.join(format!("{NAME}.appex"));
	if appex.exists() {
		std::fs::remove_dir_all(&appex)
			.with_context(|| format!("could not clear {}", appex.display()))?;
	}
	let contents = appex.join("Contents");
	copy(&binary, &contents.join("MacOS").join(NAME))?;
	write(&contents.join("Info.plist"), &info_plist(config, true, 1))?;
	// Safari reads the extension from the app extension's resources.
	copy_tree(package, &contents.join("Resources"))?;
	super::run_tool(
		Command::new("codesign")
			.args([
				"--force",
				"--sign",
				"-",
				"--timestamp=none",
				"--entitlements",
			])
			.arg(work.join("entitlements.plist"))
			.arg(&appex),
	)
	.context("signing the Safari extension")?;
	Ok(())
}

/// Copies every file under `from` to the same place under `to`.
///
/// # Errors
///
/// When a file can't be read or written.
pub fn copy_tree(from: &Path, to: &Path) -> Result<()> {
	for entry in walkdir::WalkDir::new(from) {
		let entry = entry.with_context(|| format!("could not read {}", from.display()))?;
		if entry.file_type().is_file() {
			let relative = entry.path().strip_prefix(from).expect("under its root");
			copy(entry.path(), &to.join(relative))?;
		}
	}
	Ok(())
}

#[cfg(test)]
mod tests {
	use super::*;

	fn config(browsers: &str) -> LeptoskitConfig {
		LeptoskitConfig::from_toml(
			&format!(
				"[app]\nplatforms = [\"web\", \"macos\", \"extension\"]\nversion = \
				 \"1.2.3\"\n[native]\npackage_id = \"com.example.notes\"\n[extension]\nname = \
				 \"Notes & more\"\nbrowsers = {browsers}\n[extension.popup]\nroute = \"/\"\n"
			),
			Path::new("notes"),
		)
		.unwrap()
	}

	#[test]
	fn only_apps_with_safari_carry_the_extension() {
		assert!(configured(&config("[\"chromium\", \"safari\"]")));
		assert!(!configured(&config("[\"chromium\"]")));
	}

	#[test]
	fn the_extension_s_identity_derives_from_the_app_s() {
		let config = config("[\"safari\"]");
		assert_eq!(bundle_id(&config), "com.example.notes.SafariExtension");
		let plist = info_plist(&config, true, 1);
		assert!(plist.contains("<string>com.apple.Safari.web-extension</string>"));
		assert!(plist.contains("<string>Notes &amp; more</string>"));
		assert!(plist.contains("<string>1.2.3</string>"));
		assert!(plist.contains("LSMinimumSystemVersion"));
		let ios = info_plist(&config, false, 1);
		assert!(ios.contains("MinimumOSVersion"));
		assert!(ios.contains("<string>$(CURRENT_PROJECT_VERSION)</string>"));
	}
}
