pub fn generate(
	root: &Path,
	config: &leptoskit_config::LeptoskitConfig,
	registry: &Registry,
	target: Target,
	_release: bool,
) -> Result<()> {
	let generated = root.join(".leptoskit");
	if let Ok(metadata) = std::fs::symlink_metadata(&generated) {
		anyhow::ensure!(
			metadata.is_dir() && !metadata.file_type().is_symlink(),
			".leptoskit must be an ordinary generated directory"
		);
	}
	std::fs::create_dir_all(&generated)?;
	let mut rust = String::from(
		"// Generated by leptoskit. Edit native.plugins and Cargo dependencies \
		 instead.\n#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn \
		 leptoskit_app_create_with_context(wasm: *const u8, len: usize, context: *const \
		 leptoskit_bridge_ffi::app::NativeAppContext, error: *mut leptoskit_bridge_ffi::Buffer) \
		 -> *mut leptoskit_bridge_ffi::app::App {\n    // SAFETY: The native app owns these \
		 input/output buffers for this call.\n    unsafe { \
		 leptoskit_bridge_ffi::app::create_with_context(wasm, len, context, error, |app, \
		 _context| {\n",
	);
	for plugin in &registry.plugins {
		let install = if plugin.rust_worker {
			"install_worker"
		} else {
			"install"
		};
		if let Some(kind) = &plugin.rust_type {
			writeln!(
				rust,
				"        app.{install}(Box::new({}::{kind}::default()))?;",
				plugin.crate_name
			)?;
		} else if let Some(factory) = &plugin.rust_factory {
			writeln!(
				rust,
				"        app.{install}(Box::new({}::{factory}(&_context.data_dir, \
				 &_context.cache_dir)?))?;",
				plugin.crate_name
			)?;
		} else {
			let supported = match target {
				Target::Ios | Target::IosSimulator | Target::Macos => {
					plugin.apple_module.is_some() && plugin.apple_type.is_some()
				}
				Target::Android | Target::AndroidX86_64 => plugin.android_type.is_some(),
			};
			anyhow::ensure!(
				supported,
				"plugin {} has no implementation for {target:?}",
				plugin.name
			);
		}
	}
	rust.push_str("        Ok(())\n    }) }\n}\n");
	write(&generated.join("registrant.rs"), &rust)?;
	match target {
		Target::Macos => super::desktop::generate(root, config, registry),
		Target::Ios | Target::IosSimulator => ios(root, config, registry),
		Target::Android => android(root, registry, "arm64-v8a"),
		Target::AndroidX86_64 => android(root, registry, "x86_64"),
	}
}

