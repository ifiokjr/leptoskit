fn android(root: &Path, registry: &Registry, abi: &str) -> Result<()> {
	let dir = root.join(".leptoskit/android");
	write(&dir.join("abi.txt"), abi)?;
	let sources = dir.join("sources");
	ensure_directory(&sources)?;
	// Replaced as one generated source tree; removed dependencies cannot leave
	// an old registrant or handler compiled into the next application.
	for entry in std::fs::read_dir(&sources)? {
		let path = entry?.path();
		anyhow::ensure!(
			path.is_file() && !path.is_symlink(),
			"unexpected generated source entry {}",
			path.display()
		);
		std::fs::remove_file(path)?;
	}
	std::fs::copy(
		registry.bridge.join("android/NativePlugin.kt"),
		sources.join("NativePlugin.kt"),
	)?;
	std::fs::copy(
		registry.bridge.join("mobile/LeptosKitView.kt"),
		sources.join("LeptosKitView.kt"),
	)?;
	let mut kotlin = String::from(
		"// Generated by leptoskit.\npackage dev.leptoskit.mobile\nimport \
		 android.content.Context\nimport dev.leptoskit.bridge.NativeDispatcher\nobject \
		 GeneratedPlugins {\n    fun register(context: Context, bridge: Long, dispatcher: \
		 NativeDispatcher) {\n",
	);
	for (index, plugin) in registry.plugins.iter().enumerate() {
		if plugin.rust_type.is_some() {
			continue;
		}
		writeln!(
			kotlin,
			"        dispatcher.register(bridge, {}({}))",
			plugin
				.android_type
				.as_deref()
				.context("missing Android plugin")?,
			if plugin.android_context {
				"context"
			} else {
				""
			}
		)?;
		for entry in std::fs::read_dir(plugin.directory.join("android"))? {
			let path = entry?.path();
			if path.extension().is_some_and(|extension| extension == "kt") {
				let filename = path
					.file_name()
					.context("plugin source filename missing")?
					.to_string_lossy();
				std::fs::copy(&path, sources.join(format!("{index}_{filename}")))?;
			}
		}
	}
	kotlin.push_str("    }\n}\n");
	write(&sources.join("GeneratedPlugins.kt"), &kotlin)?;
	let mut manifest =
		std::fs::read_to_string(root.join("hosts/android/app/src/main/AndroidManifest.xml"))?;
	let mut permissions = std::collections::BTreeSet::new();
	for plugin in &registry.plugins {
		permissions.extend(&plugin.android_permissions);
	}
	for permission in permissions {
		manifest = manifest.replacen(
			"<application",
			&format!("<uses-permission android:name=\"{permission}\"/>\n    <application"),
			1,
		);
	}
	write(&dir.join("AndroidManifest.xml"), &manifest)?;
	let cmake = format!(
		"cmake_minimum_required(VERSION 3.22)\nproject(leptoskit_app LANGUAGES \
		 CXX)\nadd_library(runtime STATIC IMPORTED)\nset_target_properties(runtime PROPERTIES \
		 IMPORTED_LOCATION {})\nadd_library(leptoskit_bridge_jni SHARED {} \
		 {})\ntarget_compile_features(leptoskit_bridge_jni PRIVATE \
		 cxx_std_20)\ntarget_compile_options(leptoskit_bridge_jni PRIVATE -Wall -Wextra \
		 -Werror)\ntarget_link_libraries(leptoskit_bridge_jni PRIVATE runtime log android dl m)\n",
		quote(&root.join(".leptoskit/lib/libleptoskit_bridge_ffi.a"))?,
		quote(&registry.bridge.join("android/bridge.cpp"))?,
		quote(&registry.bridge.join("mobile/app.cpp"))?
	);
	write(&dir.join("CMakeLists.txt"), &cmake)
}

fn quote(path: &Path) -> Result<String> {
	Ok(serde_json::to_string(
		path.to_str().context("native build path is not UTF-8")?,
	)?)
}
fn id(number: usize) -> String {
	format!("{number:024X}")
}
fn write(path: &Path, content: &str) -> Result<()> {
	check_output(path)?;
	if std::fs::read(path).is_ok_and(|existing| existing == content.as_bytes()) {
		return Ok(());
	}
	std::fs::write(path, content).with_context(|| format!("write {}", path.display()))
}

pub fn copy(from: &Path, to: &Path) -> Result<()> {
	check_output(to)?;
	std::fs::copy(from, to)
		.with_context(|| format!("copy {} to {}", from.display(), to.display()))?;
	Ok(())
}

fn check_output(path: &Path) -> Result<()> {
	ensure_directory(path.parent().context("generated file has no parent")?)?;
	if let Ok(metadata) = std::fs::symlink_metadata(path) {
		anyhow::ensure!(
			metadata.is_file() && !metadata.file_type().is_symlink(),
			"generated output must be a regular file: {}",
			path.display()
		);
	}
	Ok(())
}

fn ensure_directory(path: &Path) -> Result<()> {
	for parent in path.ancestors() {
		if let Ok(metadata) = std::fs::symlink_metadata(parent) {
			anyhow::ensure!(
				metadata.is_dir() && !metadata.file_type().is_symlink(),
				"generated directory must not traverse a symlink: {}",
				parent.display()
			);
		}
	}
	std::fs::create_dir_all(path)?;
	Ok(())
}
