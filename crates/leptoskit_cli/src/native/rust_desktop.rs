//! App-owned GTK and Win32 runners loading the shared application guest.

use std::io::BufRead;
use std::io::BufReader;
use std::path::Path;
use std::path::PathBuf;
use std::process::Command;
use std::process::Stdio;

use anyhow::Context;
use anyhow::Result;
use leptoskit_config::LeptoskitConfig;
use serde::Deserialize;

use super::Target;
use super::generated_dir;
use super::host_dir;
use super::project::copy;
use super::project::write;
use super::registry::Registry;

/// Validates supported desktop capabilities and generates disposable
/// registration.
pub fn generate(
	root: &Path,
	config: &LeptoskitConfig,
	registry: &Registry,
	target: Target,
) -> Result<()> {
	anyhow::ensure!(
		matches!(target, Target::Linux | Target::Windows | Target::Tui),
		"the Rust desktop runner requires Linux, Windows, or a terminal"
	);
	anyhow::ensure!(
		!config.codepush.enabled,
		"the {} runner does not support code push yet; set codepush.enabled = false before \
		 building this platform",
		target.platform()
	);
	anyhow::ensure!(
		registry.plugins.is_empty(),
		"the {} runner does not support native runtime plugins yet; remove [{}] from \
		 native.plugins before building this platform",
		target.platform(),
		registry
			.plugins
			.iter()
			.map(|plugin| plugin.name.as_str())
			.collect::<Vec<_>>()
			.join(", ")
	);
	let generated = generated_dir(root, target);

	for directory in [root.join(".leptoskit"), generated.clone()] {
		match std::fs::symlink_metadata(&directory) {
			Ok(metadata) => {
				anyhow::ensure!(
					metadata.is_dir() && !metadata.file_type().is_symlink(),
					"{} must be an ordinary generated directory",
					directory.display()
				);
			}
			Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
			Err(error) => return Err(error).context("inspect generated desktop directory"),
		}
	}

	write(
		&generated.join("registrant.rs"),
		"// Generated by leptoskit. Native desktop capabilities are not enabled.\npub fn \
		 configure<B: leptoskit::native::NativeBackend>(\n_host: &mut \
		 leptoskit::wasm::WasmHost<B>,\n) {}\n",
	)
}

#[derive(Deserialize)]
struct CargoMessage {
	reason: String,
	executable: Option<PathBuf>,
}

/// Compiles the app-owned runner and packages its guest beside the executable.
pub fn build(root: &Path, config: &LeptoskitConfig, target: Target, release: bool) -> Result<()> {
	let generated = generated_dir(root, target);
	let manifest = host_dir(root, target).join("Cargo.toml");
	anyhow::ensure!(manifest.is_file(), "missing {}", manifest.display());
	let mut command = Command::new("cargo");
	command
		.current_dir(root)
		.args(["build", "--manifest-path"])
		.arg(&manifest)
		.args(["--bins", "--target-dir"])
		.arg(generated.join("target"))
		.args([
			"--message-format=json-render-diagnostics",
			"--no-default-features",
		])
		.stdout(Stdio::piped())
		.stderr(Stdio::inherit());

	if release {
		command.arg("--release");
	} else {
		command.args(super::DEBUG_HOST_ARGUMENTS);
	}

	let mut child = command
		.spawn()
		.context("start desktop runner compilation")?;
	let stdout = child.stdout.take().context("Cargo stdout unavailable")?;
	let executable = executable_in_messages(BufReader::new(stdout));
	let status = child
		.wait()
		.context("wait for desktop runner compilation")?;
	anyhow::ensure!(status.success(), "desktop runner compilation failed");
	let executable = executable?.context("Cargo produced no desktop executable")?;
	let bundle = assemble(root, config, target, &executable)?;
	println!("built application at {}", bundle.display());
	Ok(())
}

/// Where a build puts the runner's executable: `.leptoskit/<platform>/app/`,
/// named after the app.
pub(crate) fn application(root: &Path, config: &LeptoskitConfig, target: Target) -> PathBuf {
	let name = if matches!(target, Target::Windows) || (target.builds_on_host() && cfg!(windows)) {
		format!("{}.exe", config.app.name)
	} else {
		config.app.name.clone()
	};
	generated_dir(root, target).join("app").join(name)
}

/// Reads Cargo's artifact path rather than guessing its target/profile layout.
fn executable_in_messages(messages: impl BufRead) -> Result<Option<PathBuf>> {
	let mut executable = None;

	for line in messages.lines() {
		let line = line.context("read Cargo output")?;
		let message: CargoMessage = serde_json::from_str(&line).context("parse Cargo output")?;

		if message.reason == "compiler-artifact"
			&& let Some(path) = message.executable
		{
			anyhow::ensure!(
				executable.is_none(),
				"Cargo produced multiple desktop executables"
			);
			executable = Some(path);
		}
	}

	Ok(executable)
}

fn assemble(
	root: &Path,
	config: &LeptoskitConfig,
	target: Target,
	executable: &Path,
) -> Result<PathBuf> {
	let generated = generated_dir(root, target);
	let bundle = generated.join("app");
	copy(executable, &application(root, config, target))?;
	copy(
		&generated.join("assets/app.wasm"),
		&bundle.join("assets/app.wasm"),
	)?;
	Ok(bundle)
}

#[cfg(test)]
mod tests {
	use super::*;

	#[test]
	fn rejects_unsupported_capabilities_without_replacing_registration() {
		let root = std::env::temp_dir().canonicalize().unwrap().join(format!(
			"leptoskit-desktop-registration-{}",
			std::process::id()
		));
		write(&root.join("linux/Cargo.toml"), "# owned manifest").unwrap();
		let mut registry = Registry {
			package: "desktop_linux".into(),
			plugins: Vec::new(),
			support: Vec::new(),
			bridge: root.join("bridge"),
			target: root.join("target"),
			host_features: vec![],
		};
		let mut config = LeptoskitConfig::default();
		generate(&root, &config, &registry, Target::Linux).unwrap();
		let path = root.join(".leptoskit/linux/registrant.rs");
		let original = std::fs::read(&path).unwrap();
		config.codepush.enabled = true;
		let error = generate(&root, &config, &registry, Target::Linux).unwrap_err();
		assert!(error.to_string().contains("codepush.enabled = false"));
		config.codepush.enabled = false;
		registry.plugins.push(
			serde_json::from_value(
				serde_json::json!({"name": "filesystem", "rust-type": "Plugin"}),
			)
			.unwrap(),
		);
		let error = generate(&root, &config, &registry, Target::Linux).unwrap_err();
		assert!(error.to_string().contains("filesystem"));
		assert_eq!(std::fs::read(path).unwrap(), original);
		std::fs::remove_dir_all(root).unwrap();
	}

	#[test]
	fn follows_cargos_executable_and_rejects_ambiguous_artifacts() {
		let messages = concat!(
			"{\"reason\":\"compiler-artifact\",\"executable\":null}\n",
			"{\"reason\":\"compiler-artifact\",\"executable\":\"/custom/runner.exe\"}\n",
			"{\"reason\":\"build-finished\",\"success\":true}\n"
		);
		assert_eq!(
			executable_in_messages(messages.as_bytes()).unwrap(),
			Some(PathBuf::from("/custom/runner.exe"))
		);
		let multiple = format!("{messages}{messages}");
		assert!(executable_in_messages(multiple.as_bytes()).is_err());
		assert!(executable_in_messages(b"not Cargo JSON\n".as_slice()).is_err());
	}

	#[test]
	fn bundles_a_platform_guest_and_preserves_the_owned_runner() {
		for target in [Target::Linux, Target::Windows] {
			let root = std::env::temp_dir().canonicalize().unwrap().join(format!(
				"leptoskit-desktop-bundle-{}-{}",
				std::process::id(),
				target.platform()
			));
			let host = root.join(target.platform().to_string());
			write(&host.join("Cargo.toml"), "# owned manifest").unwrap();
			write(&host.join("src/main.rs"), "// owned window").unwrap();
			let generated = generated_dir(&root, target);
			write(&generated.join("assets/app.wasm"), "platform guest").unwrap();
			write(&root.join("runner"), "executable").unwrap();
			let mut config = LeptoskitConfig::default();
			config.app.name = "desktop_test".into();
			let bundle = assemble(&root, &config, target, &root.join("runner")).unwrap();
			let name = if matches!(target, Target::Windows) {
				format!("{}.exe", config.app.name)
			} else {
				config.app.name.clone()
			};
			assert_eq!(std::fs::read(bundle.join(name)).unwrap(), b"executable");
			assert_eq!(
				std::fs::read(bundle.join("assets/app.wasm")).unwrap(),
				b"platform guest"
			);
			assert_eq!(
				std::fs::read(host.join("src/main.rs")).unwrap(),
				b"// owned window"
			);
			std::fs::remove_dir_all(root).unwrap();
		}
	}
}
