//! The iOS host's Rust side: the bridge, and the plugins
//! `leptoskit build --platform ios` registers from this crate's
//! dependencies. Empty on every other platform.

// The registrant exports C entry points for the host, which are `unsafe` by
// nature.
#![allow(unsafe_code)]

// Each plugin is named here so it counts as used before the registrant that
// installs it has been generated.
#[cfg(target_os = "ios")]
use leptoskit_bridge_ffi as _;
#[cfg(target_os = "ios")]
use leptoskit_plugin_crypto as _;
#[cfg(target_os = "ios")]
use leptoskit_plugin_http as _;
#[cfg(target_os = "ios")]
use leptoskit_plugin_passkeys as _;
#[cfg(target_os = "ios")]
use leptoskit_plugin_secure_store as _;
#[cfg(target_os = "ios")]
use leptoskit_plugin_web_auth as _;
#[cfg(target_os = "ios")]
use leptoskit_plugin_websocket as _;

/// The registrant `leptoskit build` generates, as its build copied it.
#[cfg(target_os = "ios")]
#[allow(
	clippy::all,
	clippy::pedantic,
	unused_qualifications,
	reason = "generated by leptoskit build"
)]
mod registrant {
	include!(concat!(env!("OUT_DIR"), "/registrant.rs"));
}
